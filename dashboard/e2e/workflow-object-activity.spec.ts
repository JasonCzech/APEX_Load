import { test, expect, seedScript, seedScenario, json, login } from './support/workflow'
import { createWorkspace, scopeQuery } from './support/workspace'

test('archive, restore, dependency admission and retained deleted history', async ({ page }) => {
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
  const request = page.context().request; const workspace = await createWorkspace(request)
  const name = `Activity checkout ${Date.now()}`
  const scriptId = await seedScript(request, workspace, name)
  const scenarioId = await seedScenario(request, workspace, scriptId, `${name} scenario`)
  await page.goto(`/#/scripts?mode=edit&scriptId=${scriptId}&${scopeQuery(workspace)}`); await page.reload()
  const history = page.getByRole('region', { name: 'Object history' })
  await expect(history).toContainText('Created by')
  await expect(history).not.toContainText('Created by Unknown')
  await history.getByText('History', { exact: true }).click()
  await expect(history.getByRole('table', { name: 'Object activity history' })).toContainText('create')
  await page.goto(`/#/scripts?${scopeQuery(workspace)}`); await page.reload()
  const row = page.getByRole('row').filter({ hasText: name })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.getByLabel('Script archive state').selectOption('archived')
  await expect(row).toContainText('Archived')
  const blocked = await request.post('/api/v1/tests', { data: { project_id: workspace.projectId, application_id: workspace.applicationId, release_id: workspace.releaseId, scenario_id: scenarioId, name: 'Must be blocked', duration: '1s', groups: [{ name: 'orders', script_id: scriptId, vusers: 1 }] } })
  expect(blocked.ok()).toBe(false); expect(await blocked.text()).toContain('archived')
  await page.goto(`/#/new-test?scenarioId=${scenarioId}&${scopeQuery(workspace)}`)
  await expect(page.getByRole('alert').filter({ hasText: 'blocks execution' })).toContainText(name)
  await expect(page.getByRole('button', { name: 'Start Now', exact: true })).toBeDisabled()
  await page.goto(`/#/scripts?${scopeQuery(workspace)}`)
  await page.getByLabel('Script archive state').selectOption('archived')
  await row.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.getByLabel('Script archive state').selectOption('active'); await expect(row).toBeVisible()
  const current = await json(await request.get(`/api/v1/scripts/${scriptId}`))
  expect(current.activity).toBeTruthy()
  await page.goto(`/#/tests?view=library&${scopeQuery(workspace)}`)
  const scenarioRow = page.getByRole('row').filter({ hasText: `${name} scenario` })
  await scenarioRow.getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(scenarioRow).toHaveCount(0)
  await page.getByLabel('Scenario archive state').selectOption('archived')
  await expect(scenarioRow).toContainText('Archived')
  await scenarioRow.getByRole('button', { name: 'Restore', exact: true }).click()
  await json(await request.delete(`/api/v1/scenarios/${scenarioId}`))
  await json(await request.delete(`/api/v1/scripts/${scriptId}`))
  await page.goto(`/#/activity?${scopeQuery(workspace)}`); await page.reload()
  await expect(page.getByRole('heading', { name: 'Activity', exact: true })).toBeVisible()
  await page.getByLabel('Object name', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  const events = page.getByRole('table', { name: 'Object activity history' })
  await expect(events).toContainText(`${name} (deleted)`); await expect(events).toContainText('archive'); await expect(events).toContainText('restore')
  await expect(events.getByRole('link', { name })).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('deleted-object-history.png'), fullPage: true, animations: 'disabled' })
})


test('saved changes show audit warnings without implying failure', async ({ page }) => {
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
  const request = page.context().request; const workspace = await createWorkspace(request)
  const id = await seedScript(request, workspace, `Warning saved ${Date.now()}`)
  await page.goto(`/#/scripts?${scopeQuery(workspace)}`); await page.reload()
  await page.route(`**/api/v1/scripts/${id}/archive`, async route => {
    const response = await route.fetch()
    await route.fulfill({ response, headers: { ...response.headers(), 'X-APEXLOAD-Audit-Status': 'unavailable' } })
  })
  await page.getByRole('row').filter({ hasText: 'Warning saved' }).getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Change saved; activity history could not be recorded.' })).toBeVisible()
  const saved = await json(await request.get(`/api/v1/scripts/${id}`)); expect(saved.archived_at).toBeTruthy()
})

test('project viewers can inspect deleted history but cannot archive or restore', async ({ page }) => {
  test.skip(process.env.APEXLOAD_E2E_PROFILE !== 'local-auth', 'requires the local viewer persona')
  await login(page)
  const request = page.context().request; const workspace = await createWorkspace(request)
  const name = `Viewer history ${Date.now()}`; const id = await seedScript(request, workspace, name)
  const deletedId = await seedScript(request, workspace, name + ' deleted')
  await json(await request.delete(`/api/v1/scripts/${deletedId}`))
  const users = (await json(await request.get('/api/v1/auth/users'))).users as Array<{ id: string; subject: string }>
  const viewer = users.find(user => user.subject === 'local:user')!
  await json(await request.post(`/api/v1/auth/users/${viewer.id}/bindings`, { data: { scope_type: 'domain', scope_id: workspace.domainId, role: 'viewer' } }))
  await page.getByRole('button', { name: 'Sign out' }).click(); await login(page, 'user')
  await page.goto(`/#/scripts?${scopeQuery(workspace)}`); await page.reload()
  await expect(page.getByRole('row').filter({ hasText: name })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Archive', exact: true })).toHaveCount(0)
  expect((await request.post(`/api/v1/scripts/${id}/archive`, { data: {} })).status()).toBe(403)
  expect((await request.post(`/api/v1/scripts/${id}/restore`, { data: {} })).status()).toBe(403)
  await page.goto(`/#/activity?${scopeQuery(workspace)}`)
  await page.getByLabel('Object name', { exact: true }).fill(name + ' deleted')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('table', { name: 'Object activity history' })).toContainText(name + ' deleted (deleted)')
})
