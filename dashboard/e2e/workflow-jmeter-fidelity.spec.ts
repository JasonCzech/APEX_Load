import { readFile } from 'node:fs/promises'
import http from 'node:http'
import path from 'node:path'
import { test, expect, login, mutation, json } from './support/workflow'
import { createWorkspace, scopeQuery } from './support/workspace'

const fixture = (name: string) => path.join(process.cwd(), '..', 'pkg', 'convert', 'jmeter', 'testdata', `split_pay_${name}.jmx`)

test('JMeter fidelity review retains blockers and regenerates explicit timestamp and name repairs', async ({ page }) => {
  test.setTimeout(120_000)
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
  const workspace = await createWorkspace(page.context().request)
  await page.goto(`/#/scripts?mode=create&${scopeQuery(workspace)}`)
  await page.reload()
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Find a source format' }).fill('JMeter')
  await page.locator('.script-create-option').click()
  const controls = page.getByRole('group', { name: 'Script import controls' })
  await controls.locator('input[type=file]').setInputFiles(fixture('original'))
  const inspected = mutation(page, 'POST', '/api/v1/scripts/import/jmeter')
  await controls.getByRole('button', { name: 'Inspect & review', exact: true }).click()
  const before = await json(await inspected)
  expect(JSON.stringify(before)).toContain('jmeter_timestamp_timezone_required')
  expect(before.scenario_draft).toMatchObject({ termination_mode: 'iterations', duration: '', groups: [expect.objectContaining({ vusers: 50, iterations: 200, ramp_up: '1s' })] })
  await controls.getByRole('tab', { name: 'Source Mapping', exact: true }).click()
  await expect(controls.getByRole('tabpanel')).toContainText('Source')
  await controls.locator('.import-source-setup > summary').click()
  await expect(controls.getByText(/Declared source names:/)).toContainText('cid')
  await controls.getByLabel('Bind client_id', { exact: true }).fill('cid')
  await controls.getByLabel('Bind client_secret', { exact: true }).fill('cs')
  await controls.getByLabel('Timestamp policy', { exact: true }).selectOption('utc')
  const repaired = mutation(page, 'POST', '/api/v1/scripts/import/jmeter')
  await controls.getByRole('button', { name: 'Inspect & review', exact: true }).click()
  const after = await json(await repaired)
  expect(JSON.stringify(after)).not.toContain('jmeter_timestamp_timezone_required')
  expect(JSON.stringify(after)).toContain('execution_blocker')
  expect(after).toMatchObject({ scripts: [expect.objectContaining({ config: expect.objectContaining({ results: { csv_exports: [expect.objectContaining({ file_name: 'traceId-results.csv' })] } }) })] })
})

test('JMeter repaired import saves finite workload and downloads native per-run CSV', async ({ page }) => {
  test.setTimeout(120_000)
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
  let samples = 0
  const target = http.createServer((_req, res) => { samples++; res.setHeader('content-type', 'application/json'); res.end(JSON.stringify({ idpTraceId: `trace-${samples}` })) })
  await new Promise<void>(resolve => target.listen(0, '127.0.0.1', resolve))
  try {
    const address = target.address()
    if (!address || typeof address === 'string') throw new Error('loopback target did not bind')
    const request = page.context().request
    const workspace = await createWorkspace(request)
    await page.goto(`/#/scripts?mode=create&${scopeQuery(workspace)}`)
    await page.reload()
    await page.getByRole('button', { name: 'Import', exact: true }).click()
    await page.getByRole('searchbox', { name: 'Find a source format' }).fill('JMeter')
    await page.locator('.script-create-option').click()
    const controls = page.getByRole('group', { name: 'Script import controls' })
    const source = (await readFile(fixture('repaired'), 'utf8')).replace('name="ThreadGroup.num_threads">50<', 'name="ThreadGroup.num_threads">2<').replace('name="LoopController.loops">200<', 'name="LoopController.loops">3<')
    await controls.locator('input[type=file]').setInputFiles({ name: 'small-repaired.jmx', mimeType: 'application/xml', buffer: Buffer.from(source) })
    await controls.getByLabel('Base URL Override', { exact: true }).fill(`http://127.0.0.1:${address.port}`)
    await controls.getByLabel('Timestamp policy', { exact: true }).selectOption('utc')
    const inspected = mutation(page, 'POST', '/api/v1/scripts/import/jmeter')
    await controls.getByRole('button', { name: 'Inspect & review', exact: true }).click()
    const payload = await json(await inspected)
    expect(payload.scenario_draft).toMatchObject({ termination_mode: 'iterations' })
    await controls.getByRole('tab', { name: 'Runtime settings', exact: true }).click()
    await expect(controls.getByRole('tabpanel')).toContainText('2 VUsers × 3 iterations')
    await controls.getByRole('tab', { name: 'Review', exact: true }).click()
    const saved = mutation(page, 'POST', '/api/v1/scripts/import/jmeter/save')
    await controls.getByRole('button', { name: 'Save 1 draft', exact: true }).click()
    const stored = await json(await saved)
    const storedScenario = stored.scenario as { id: string; termination_mode: string }
    expect(storedScenario.termination_mode).toBe('iterations')
    const run = await json(await request.post('/api/v1/tests', { data: { name: 'JMeter finite browser run', scenario_id: storedScenario.id, application_id: workspace.applicationId, release_id: workspace.releaseId } }))
    await json(await request.post(`/api/v1/tests/${run.id}/start`))
    await expect.poll(async () => (await json(await request.get(`/api/v1/tests/${run.id}`))).status, { timeout: 60_000 }).toBe('COMPLETE')
    expect(samples).toBe(6)
    await expect.poll(async () => (await request.get(`/api/v1/tests/${run.id}/archive/manifest`)).ok()).toBe(true)
    const csv = await request.get(`/api/v1/tests/${run.id}/archive/files/traceId-results.csv`)
    expect(csv.ok(), await csv.text()).toBeTruthy()
    expect((await csv.text()).trim().split('\n')).toHaveLength(7)
    expect((await csv.text()).split('\n')[0]).toBe('traceId,latencyMs')
    await page.goto(`/#/test/${run.id}?tab=archive&${scopeQuery(workspace)}`)
    await page.getByText('Raw evidence downloads', { exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Download traceId-results.csv', exact: true }).click()
    const download = await downloadPromise
    expect(download.suggestedFilename()).toBe('traceId-results.csv')
  } finally { await new Promise<void>((resolve, reject) => target.close(err => err ? reject(err) : resolve())) }
})

test('JMeter messaging preview preserves three blocked drafts and workload curves', async ({ page }, testInfo) => {
  test.setTimeout(120_000)
  await page.setViewportSize({ width: 1440, height: 1600 })
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
  const request = page.context().request
  const workspace = await createWorkspace(request)
  await page.goto(`/#/scripts?mode=create&${scopeQuery(workspace)}`)
  await page.reload()
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Find a source format' }).fill('JMeter')
  await page.locator('.script-create-option').click()
  const controls = page.getByRole('group', { name: 'Script import controls' })
  await controls.locator('input[type=file]').setInputFiles(path.join(process.cwd(), '..', 'pkg', 'convert', 'jmeter', 'testdata', 'messaging_original.jmx'))
  const inspected = mutation(page, 'POST', '/api/v1/scripts/import/jmeter')
  await controls.getByRole('button', { name: 'Inspect & review', exact: true }).click()
  const payload = await json(await inspected)
  expect(payload.scripts).toHaveLength(3)
  expect(payload.scenario_draft).toMatchObject({ duration: '1h5m0s', generator_affinity: 'single_generator' })
  const fidelity = controls.getByRole('region', { name: 'Messaging fidelity' })
  await expect(fidelity).toContainText('3/3 enabled workload samplers mapped')
  await expect(fidelity).toContainText('630,450')
  await expect(fidelity).toContainText('replay blocked')
  await expect(fidelity.getByRole('img')).toHaveCount(3)
  await fidelity.scrollIntoViewIfNeeded()
  await fidelity.screenshot({ path: testInfo.outputPath('messaging-fidelity.png') })
  await fidelity.locator('summary').click()
  await expect(fidelity).toContainText('9999999')
  await expect(fidelity).toContainText('16384')
  const saved = await json(await request.post('/api/v1/scripts/import/jmeter/save', { data: { scripts: payload.scripts, scenario_draft: payload.scenario_draft } }))
  expect(saved.scripts).toHaveLength(3)
  expect(saved.scenario).toMatchObject({ duration: '1h5m0s', assignment: { source_affinity: 'single_generator' } })
  const scenarioID = (saved.scenario as { id: string }).id
  const reopened = await json(await request.get(`/api/v1/scenarios/${scenarioID}`))
  expect(reopened.assignment).toMatchObject({ source_affinity: 'single_generator' })
  const attempt = await request.post('/api/v1/tests', { data: { name: 'Messaging remains blocked', scenario_id: scenarioID, application_id: workspace.applicationId, release_id: workspace.releaseId } })
  expect(attempt.status()).toBeGreaterThanOrEqual(400)
})
