import { test, expect, login, seedScript, mutation, json, idOf, runStatus } from './support/workflow'
import { createWorkspace, scopeQuery } from './support/workspace'

test.beforeEach(async ({ page }) => {
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
})

test('missing Base URL is a local problem with a focused repair path', async ({ page }) => {
  const request = page.context().request
  const workspace = await createWorkspace(request)
  const id = await seedScript(request, workspace)
  await page.goto(`/#/scripts?mode=edit&scriptId=${id}&${scopeQuery(workspace)}`)
  await page.reload()
  await page.getByRole('tab', { name: 'Runtime Settings', exact: true }).click()
  const input = page.getByRole('textbox', { name: 'Base URL', exact: true })
  await expect(input).toHaveAttribute('required', '')
  await input.fill('')
  await page.getByRole('button', { name: 'Save script', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Base URL is required')
  await dialog.getByRole('button', { name: /Base URL is required/ }).click()
  await expect(input).toBeFocused()
  await input.fill('http://127.0.0.1:12345')
  const saved = mutation(page, 'PUT', `/api/v1/scripts/${id}`)
  await page.getByRole('button', { name: 'Save script', exact: true }).click()
  await json(await saved)
})

for (const width of [1440, 932]) {
  test(`script catalog retry clears the error and its notice stays below the header at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const request = page.context().request
    const workspace = await createWorkspace(request)
    const pattern = '**/api/v1/scripts?*'
    await page.route(pattern, route => route.fulfill({ status: 503, json: { error: 'Catalog temporarily unavailable' } }))
    await page.goto(`/#/scripts?${scopeQuery(workspace)}`)
    await page.reload()
    const retry = page.getByRole('button', { name: 'Retry loading scripts' })
    await expect(retry).toBeVisible()
    const notice = retry.locator('..')
    const header = await page.locator('.main-topbar').boundingBox()
    const banner = await notice.boundingBox()
    expect(header && banner && banner.y >= header.y + header.height).toBeTruthy()
    await page.unroute(pattern)
    await retry.click()
    await expect(notice).toBeHidden()
    await expect(page.getByText('Catalog temporarily unavailable', { exact: false })).toBeHidden()
  })
}

test('stopped outcomes and report drill-down agree across populations', async ({ page, target, trackRun }) => {
  const request = page.context().request
  const workspace = await createWorkspace(request)
  const scriptId = await seedScript(request, workspace, 'Crosscut_population', target.url)
  const run = await json(await request.post('/api/v1/tests', { data: { project_id: workspace.projectId, application_id: workspace.applicationId, release_id: workspace.releaseId, name: 'Crosscut stopped run', duration: '5m', groups: [{ name: 'orders', script_id: scriptId, vusers: 1 }] } }))
  const id = idOf(run); trackRun(id)
  await json(await request.post(`/api/v1/tests/${id}/start`))
  await expect.poll(() => target.count()).toBeGreaterThan(2)
  await json(await request.post(`/api/v1/tests/${id}/stop`))
  await expect.poll(() => runStatus(request, id), { timeout: 60000 }).toBe('COMPLETE')
  await expect.poll(async () => (await request.get(`/api/v1/tests/${id}/archive/report`)).ok()).toBe(true)
  await page.goto(`/#/results?${scopeQuery(workspace)}`)
  await page.reload()
  await page.getByRole('searchbox', { name: 'Search results', exact: true }).fill('Crosscut stopped run')
  const row = page.locator('tbody tr').filter({ hasText: 'Crosscut stopped run' })
  await expect(row).toContainText('Stopped by operator')
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('complete')
  await expect(row).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('stopped')
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'View results' }).click()
  await page.getByRole('tab', { name: 'Performance', exact: true }).click()
  await page.locator('.run-report-scoreboard .run-report-table tbody tr').filter({ hasText: 'Crosscut_population' }).click()
  await expect(page.getByRole('combobox', { name: 'Metric population', exact: true })).toHaveValue('transaction')
  await expect(page.getByRole('heading', { name: 'Named transaction summary', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Diagnostics', exact: true }).click()
  const selector = page.getByRole('combobox', { name: 'Archived named transaction' })
  await expect(selector).toBeVisible()
  await expect(selector.locator('option')).not.toHaveCount(0)
  const name = await selector.inputValue()
  const response = await request.get(`/api/v1/tests/${id}/archive/transactions?population=transaction&action=${encodeURIComponent(name)}`)
  const evidence = await response.json()
  expect(evidence.total).toBeGreaterThan(0)
  expect(evidence.transactions.every((event: { population: string }) => event.population === 'transaction')).toBe(true)
  await expect(page.locator('.archive-drilldown-stat').first()).toContainText(`${evidence.total} total`)
  await page.getByRole('combobox', { name: 'Metric population', exact: true }).selectOption('action')
  await expect(page.getByRole('combobox', { name: 'Archived action', exact: true })).toHaveValue('orders')
  await page.goto(`/#/monitoring?${scopeQuery(workspace)}`)
  await page.getByRole('tablist', { name: 'Monitor categories' }).getByRole('tab', { name: 'Schedules', exact: true }).click()
  await expect(page.locator('.run-calendar-event').filter({ hasText: 'Crosscut stopped run' }).first()).toContainText('Stopped by operator')
})

test('nested script editor owns title and help and returns the scenario context', async ({ page }) => {
  const request = page.context().request
  const workspace = await createWorkspace(request)
  await page.goto(`/#/tests?view=builder&${scopeQuery(workspace)}`)
  await page.reload()
  await page.getByPlaceholder('Scenario name').fill('Retained scenario')
  await page.getByRole('button', { name: 'Add script to Group 1' }).click()
  await page.getByRole('dialog', { name: 'Choose script' }).getByRole('button', { name: 'Create script', exact: true }).click()
  await page.getByRole('tab', { name: /Blank & Assisted Editors/ }).click()
  await page.getByRole('button', { name: /API Visual Editor/ }).click()
  await expect(page.locator('.main-topbar h1')).not.toHaveText('Scenarios')
  await expect(page.getByRole('link', { name: 'Help for this page', exact: true })).toHaveAttribute('href', /article=authoring/)
  await page.getByRole('button', { name: 'Back to scenario draft' }).click()
  const discard = page.getByRole('button', { name: 'Discard changes', exact: true })
  if (await discard.isVisible()) await discard.click()
  await expect(page.getByPlaceholder('Scenario name')).toHaveValue('Retained scenario')
  await expect(page.locator('.main-topbar h1')).toHaveText('Scenarios')
  await expect(page.getByRole('button', { name: 'Scenario builder', pressed: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Help for this page', exact: true })).toHaveAttribute('href', /article=scenarios/)
})
