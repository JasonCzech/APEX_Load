import { test, expect, json, idOf, login, seedScript, seedScenario, signOut } from './support/workflow'
import { createWorkspace, scopeQuery } from './support/workspace'

test('Library assignments persist, bulk failures recover, and launches require an explicit release', async ({ page }, testInfo) => {
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
  const request = page.context().request
  const workspace = await createWorkspace(request)
  const first = await seedScript(request, workspace, 'Assigned_First')
  const second = await seedScript(request, workspace, 'Assigned_Second')
  const scenario = await seedScenario(request, workspace, first, 'Assigned_Scenario')
  await seedScenario(request, workspace, second, 'Bulk_Assigned_Scenario')
  const original = await json(await request.get(`/api/v1/scripts/${first}`))
  const release = await json(await request.get(`/api/v1/applications/${workspace.applicationId}/releases`))
  const releaseId = (release.releases as Array<{id:string}>)[0].id
  await page.goto(`/#/scripts?${scopeQuery(workspace)}`)
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await page.reload()
  const row = page.locator('.scripts-library-table tbody tr').filter({ hasText: 'Assigned_First' })
  await row.getByText('More', { exact: true }).click()
  await row.getByRole('button', { name: 'Change application/releases…' }).click()
  const dialog = page.getByRole('dialog', { name: 'Change application/releases', exact: true })
  await dialog.getByLabel('Application', { exact: true }).selectOption(workspace.applicationId)
  await dialog.getByRole('checkbox').first().check()
  await page.screenshot({ path: testInfo.outputPath('library-assignment-dialog.png'), animations: 'disabled' })
  // Another operator changes the assignment after this dialog opens.
  await json(await request.put(`/api/v1/scripts/${first}/library-assignment`, { data: { application_id: workspace.applicationId, release_ids: [], expected_revision: 0 } }))
  await dialog.getByRole('button', { name: 'Apply assignment' }).click()
  await expect(dialog.getByRole('button', { name: 'Retry failed assignments' })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Reload conflicting assignments' }).click()
  await dialog.getByRole('button', { name: 'Apply assignment' }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await expect(row.locator('[aria-label="Assignment"]')).not.toHaveText('Unassigned')
  await page.getByLabel('Assigned application', { exact: true }).selectOption(workspace.applicationId)
  await expect(page.locator('.scripts-library-table tbody tr').filter({ hasText: 'Assigned_Second' })).toHaveCount(0)
  await page.getByLabel('Assigned application', { exact: true }).selectOption('all')
  await page.getByLabel('Select all scripts on this page', { exact: true }).check()
  await page.getByRole('button', { name: 'Change application/releases…', exact: true }).filter({ visible: true }).first().click()
  await dialog.getByLabel('Application', { exact: true }).selectOption(workspace.applicationId)
  let secondAttempts = 0
  page.on('request', req => { if (req.method() === 'PUT' && req.url().endsWith(`/scripts/${second}/library-assignment`)) secondAttempts++ })
  await page.route(`**/scripts/${second}/library-assignment`, route => route.fulfill({ status: 500, json: { error: 'Temporary assignment failure' } }))
  await dialog.getByRole('button', { name: 'Apply assignment' }).click()
  await expect(dialog).toContainText('failed 1')
  await page.unroute(`**/scripts/${second}/library-assignment`)
  await dialog.getByRole('button', { name: 'Retry failed assignments' }).click()
  await expect(dialog).toBeHidden()
  expect(secondAttempts).toBe(2)
  const updated = await json(await request.get(`/api/v1/scripts/${first}`))
  expect(updated.script).toEqual(original.script)
  await page.goto(`/#/tests?view=library&${scopeQuery(workspace)}`)
  const scenarioRow = page.locator('.scenario-library-table tbody tr').filter({ has: page.getByText('Assigned_Scenario', { exact: true }) })
  await scenarioRow.getByText('More', { exact: true }).click()
  await scenarioRow.getByRole('button', { name: 'Change application/releases…' }).click()
  await dialog.getByLabel('Application', { exact: true }).selectOption(workspace.applicationId)
  await dialog.getByRole('checkbox').first().check()
  await dialog.getByRole('button', { name: 'Apply assignment' }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await expect(scenarioRow.locator('[aria-label="Assignment"]')).not.toHaveText('Unassigned')
  await page.getByLabel('Select all scenarios on this page', { exact: true }).check()
  await page.getByRole('button', { name: 'Change application/releases…', exact: true }).filter({ visible: true }).first().click()
  await dialog.getByLabel('Application', { exact: true }).selectOption(workspace.applicationId)
  await dialog.getByRole('checkbox').first().check()
  await dialog.getByRole('button', { name: 'Apply assignment' }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await expect(page.locator('.scenario-library-table tbody tr').filter({ hasText: 'Bulk_Assigned_Scenario' }).locator('[aria-label="Assignment"]')).not.toHaveText('Unassigned')
  const storedScenario = await json(await request.get(`/api/v1/scenarios/${scenario}`))
  expect(JSON.stringify(storedScenario.scripts)).toContain(first)
  await page.goto(`/#/new-test?scenarioId=${scenario}&${scopeQuery(workspace)}`)
  await expect(page.getByLabel('Release', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Release', { exact: true }).locator('option').filter({ hasText: 'assigned' })).toHaveCount(1)
  await page.getByLabel('Release', { exact: true }).selectOption(releaseId)
  await expect(page.getByLabel('Release', { exact: true })).toHaveValue(releaseId)
  const other = idOf(await json(await request.post('/api/v1/applications', { data: { name: 'Assignment override', project_id: workspace.projectId } })))
  await page.reload()
  await page.getByLabel('Release', { exact: true }).selectOption(releaseId)
  await page.getByLabel('Launch application', { exact: true }).selectOption(other)
  await expect(page.getByLabel('Release', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '+ New Release', exact: true }).click()
  await page.getByLabel('New release name', { exact: true }).fill('Override release')
  await page.route(`**/applications/${other}/releases`, route => route.request().method() === 'POST'
    ? route.fulfill({ status: 503, json: { error: 'Release creation temporarily unavailable' } }) : route.continue())
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Release creation temporarily unavailable' })).toBeVisible()
  await page.unroute(`**/applications/${other}/releases`)
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByLabel('Release', { exact: true }).locator('option').filter({ hasText: 'Override release' })).toHaveCount(1)
  await expect(page.getByRole('alert').filter({ hasText: 'Release creation temporarily unavailable' })).toHaveCount(0)
  const overrideReleases = await json(await request.get(`/api/v1/applications/${other}/releases`))
  const createdRelease = (overrideReleases.releases as Array<{ id: string; name: string }>).find(item => item.name === 'Override release')!
  await expect(page.getByLabel('Release', { exact: true })).toHaveValue(createdRelease.id)
  await expect(page.getByLabel('Launch application', { exact: true })).toHaveValue(other)
})

test('Viewer cannot change script or scenario assignments', async ({ page }) => {
  test.skip(process.env.APEXLOAD_E2E_PROFILE !== 'local-auth', 'requires viewer persona')
  await login(page)
  const request = page.context().request
  const workspace = await createWorkspace(request)
  const script = await seedScript(request, workspace, 'Read_only_assignment')
  const scenario = await seedScenario(request, workspace, script, 'Read_only_scenario_assignment')
  const users = (await json(await request.get('/api/v1/auth/users'))).users as Array<{id:string;subject:string}>
  const viewer = users.find(user => user.subject === 'local:user')!
  await json(await request.post(`/api/v1/auth/users/${viewer.id}/bindings`, { data: { scope_type: 'domain', scope_id: workspace.domainId, role: 'viewer' } }))
  await signOut(page)
  await login(page, 'user')
  for (const [kind,id] of [['scripts',script],['scenarios',scenario]]) {
    await page.goto(`/#/${kind === 'scenarios' ? 'tests?view=library&' : 'scripts?'}${scopeQuery(workspace)}`); await page.reload()
    await expect(page.locator(kind === 'scripts' ? '.scripts-library-table' : '.scenario-library-table')).toContainText(kind === 'scripts' ? 'Read_only_assignment' : 'Read_only_scenario_assignment')
    await expect(page.getByRole('button', { name: 'Change application/releases…' })).toHaveCount(0)
    expect((await request.put(`/api/v1/${kind}/${id}/library-assignment`, {data:{application_id:null,release_ids:[],expected_revision:0}})).status()).toBe(403)
  }
})
