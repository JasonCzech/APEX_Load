for (const status of [200,503]) {
 test(`debug ${status} shows response evidence without weakening the contract`,async({page,request,target})=>{
  const workspace=await createWorkspace(request)
  const scriptId=await seedScript(request,workspace,`Debug_${status}`,target.url,status===503?'/unavailable':'/orders')
  await page.goto(`/#/scripts?mode=edit&scriptId=${scriptId}&${scopeQuery(workspace)}`)
  await page.getByRole('group',{name:'Script workspace'}).getByRole('button',{name:'Debug',exact:true}).click()
  await page.getByTitle('Run Replay',{exact:true}).click()
  await expect(page.getByText(status===503?'Debugger completed with failures':'Debugger completed successfully',{exact:true})).toBeVisible()
  await page.getByRole('region',{name:'Debugger actions'}).getByRole('button',{name:/orders/}).click()
  const evidence=page.getByRole('region',{name:'Response evidence'})
  await expect(evidence).toContainText(`Actual response: ${status}`)
  if(status===503){
   await expect(evidence).toContainText('Service unavailable')
   await expect(page.getByText('Investigate target availability and the response evidence.',{exact:false})).toBeVisible()
   await expect(page.getByText('narrow the assertion',{exact:false})).toHaveCount(0)
  } else await expect(evidence).toContainText('not captured')
 })
}


test('first-use screens meet automated WCAG AA checks in dark and light themes',async({page,request})=>{
 await page.addInitScript({content:axe.source})
 const workspace=await createWorkspace(request)
 for(const theme of ['dark','light']) {
  await page.emulateMedia({reducedMotion:'reduce'})
  for(const [route,title] of [['dashboard','Dashboard'],['settings','Settings']]) {
   await page.goto(`/#/${route}?${scopeQuery(workspace)}`)
   await expect(page.getByRole('heading',{name:title,level:1,exact:true})).toBeVisible()
   await page.getByRole('combobox',{name:'Dashboard color theme'}).selectOption(theme)
   await page.addStyleTag({content:'* {animation:none!important;transition:none!important}'})
   const violations=await page.evaluate(async()=>{
    const scanner=(window as unknown as {axe:typeof import('axe-core')}).axe
    const result=await scanner.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})
    return result.violations.map(violation=>({id:violation.id,nodes:violation.nodes.map(node=>({target:node.target,summary:node.failureSummary}))}))
   })
   expect(violations,`${route} in ${theme}`).toEqual([])
  }
 }
})
