test('HTTP method edits preserve action type through save and reload', async ({page,request}) => {
  const workspace = await createWorkspace(request)
  const id = await seedScript(request, workspace)
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto(`/#/scripts?mode=edit&scriptId=${id}&${scopeQuery(workspace)}`)
  const workbench = page.getByRole('region', {name:'Author center workbench'})
  await page.getByRole('navigation', { name: 'Script outline' }).getByRole('button', { name: /orders.*(?:GET|POST)/ }).click()
  await expect(workbench.getByLabel('Name', { exact: true })).toHaveValue('orders')
  await expect(page.getByLabel('HTTP method', {exact:true})).toHaveValue('GET')
  await page.getByLabel('HTTP method', {exact:true}).selectOption('POST')
  const saved = mutation(page,'PUT',`/api/v1/scripts/${id}`)
  await page.getByRole('button',{name:'Save script',exact:true}).click()
  await json(await saved)
  await page.reload()
  await page.getByRole('navigation', { name: 'Script outline' }).getByRole('button', { name: /orders.*(?:GET|POST)/ }).click()
  await expect(workbench.getByLabel('Name', { exact: true })).toHaveValue('orders')
  await expect(page.getByLabel('HTTP method', {exact:true})).toHaveValue('POST')
  const stored = await json(await request.get(`/api/v1/scripts/${id}`))
  expect((stored.script as {actions:unknown[]}).actions[0]).toMatchObject({type:'request',method:'POST'})
})

test('an operator-stopped run without SLAs never produces a passing executive report', async ({page,request,target,trackRun}) => {
  const workspace = await createWorkspace(request)
  const scriptId = await seedScript(request,workspace,'Report_integrity',target.url)
  const run = await json(await request.post('/api/v1/tests',{data:{project_id:workspace.projectId,application_id:workspace.applicationId,release_id:workspace.releaseId,name:'Stopped acceptance audit',duration:'5m',groups:[{name:'orders',script_id:scriptId,vusers:1}]}}))
  const id=idOf(run);trackRun(id)
  await json(await request.post(`/api/v1/tests/${id}/start`))
  await expect.poll(()=>target.count()).toBeGreaterThan(1)
  await json(await request.post(`/api/v1/tests/${id}/stop`))
  await expect.poll(()=>runStatus(request,id),{timeout:60_000}).toBe('COMPLETE')
  await expect.poll(async()=>(await request.get(`/api/v1/tests/${id}/archive/report`)).ok()).toBe(true)
  const report=await json(await request.get(`/api/v1/tests/${id}/archive/report`))
  expect(report.verdict).toMatchObject({status:'Not assessed'})
  expect(report.manifest).toMatchObject({termination_reason:'operator_stopped'})
  const html=await (await request.get(`/api/v1/tests/${id}/report?profile=executive`)).text()
  expect(html).not.toContain('met its SLA targets')
  expect(html).not.toContain('State the recommended release decision')
  await page.goto(`/#/test/${id}?tab=archive&${scopeQuery(workspace)}`)
  await page.getByRole('tab',{name:'Summary',exact:true}).click()
  await expect(page.getByRole('region',{name:'Run outcome'})).toContainText('Stopped by operator')
  await expect(page.getByRole('region',{name:'Run outcome'})).toContainText('Not assessed')
  await expect(page.getByRole('textbox',{name:'Test execution workspace profile name'})).toBeHidden()
  await expect(page.getByRole('button',{name:'Customize view',exact:true})).toBeHidden()
  await page.getByRole('tab',{name:'Execution',exact:true}).click()
  await expect(page.getByRole('region',{name:'Execution groups'})).toBeVisible()
})

