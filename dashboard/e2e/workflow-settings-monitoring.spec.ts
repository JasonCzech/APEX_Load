import { test, expect } from './support/workflow'
import { createWorkspace, scopeQuery } from './support/workspace'

for (const width of [1024, 1280, 1440]) {
  test(`Settings navigation and canonical editors at ${width}px`, async ({ page, request }) => {
    const workspace = await createWorkspace(request)
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(`/#/settings?setting=grafana&${scopeQuery(workspace)}`)
    await expect(page.getByRole('heading', { name: 'Grafana', exact: true })).toBeVisible()
    await expect(page.getByText('Applies to: Entire deployment', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: /Reset.*Defaults/ })).toBeHidden()
    const browse = page.getByRole('button', { name: 'Expand Settings navigation' })
    if (await browse.isVisible()) await browse.click()
    await page.getByRole('searchbox', { name: 'Find settings' }).fill('OpenSearch')
    await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'OpenSearch', exact: true }).click()
    await expect(page).toHaveURL(/setting=opensearch/)
    await expect(page.getByRole('heading', { name: 'OpenSearch', exact: true })).toBeVisible()
    await page.goBack()
    await expect(page.getByRole('heading', { name: 'Grafana', exact: true })).toBeVisible()
    expect(new URLSearchParams(new URL(page.url()).hash.split('?')[1]).get('projectId')).toBe(workspace.projectId)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.goto(`/#/settings?setting=pools&${scopeQuery(workspace)}`)
    await page.getByRole('button', { name: 'New Pool', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'New Pool', exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByText('Advanced lifecycle & admission policy', { exact: true })).toBeVisible()
    expect(await dialog.evaluate(element => {
      const heading = element.querySelector('h3')!
      const rect = heading.getBoundingClientRect()
      return element.contains(document.elementFromPoint(rect.left + 2, rect.top + rect.height / 2)) && getComputedStyle(element).backgroundColor !== 'rgba(0, 0, 0, 0)'
    })).toBe(true)
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.goto(`/#/monitoring?category=alerts&${scopeQuery(workspace)}`)
    await expect(page.getByRole('tab', { name: /Alerts/ })).toHaveAttribute('aria-selected', 'true')
    await page.getByRole('link', { name: 'Notification routes', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Notification routes', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Return to originating workflow', exact: true }).click()
    await expect(page.getByRole('tab', { name: /Alerts/ })).toHaveAttribute('aria-selected', 'true')
    await page.goto(`/#/access?setting=redaction&${scopeQuery(workspace)}`)
    await page.getByText('Validate rules and preview redaction', { exact: true }).click()
    await page.getByRole('button', { name: 'Validate and preview', exact: true }).click()
    await expect(page.getByLabel('Redacted sample', { exact: true })).toContainText('[REDACTED]')
  })
}

test('settings destination navigation preserves unsaved edits until explicitly discarded', async ({ page, request }) => {
  const workspace = await createWorkspace(request)
  await page.goto(`/#/settings?setting=grafana&${scopeQuery(workspace)}`)
  await page.getByRole('textbox', { name: 'Grafana server URL' }).fill('https://draft.example.test')
  await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'Prometheus', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Grafana server URL' })).toHaveValue('https://draft.example.test')
  await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'Prometheus', exact: true }).click()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Prometheus', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('textbox', { name: 'Grafana server URL' })).not.toHaveValue('https://draft.example.test')
})

test('infrastructure guide, saved commitments and independent cancel work with keyboard navigation', async ({ page, request }) => {
  const workspace = await createWorkspace(request)
  await page.goto(`/#/settings?setting=allocations&${scopeQuery(workspace)}`)
  await page.getByText('Infrastructure setup guide', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Execution environment')).toBeVisible()
  await page.getByLabel('Execution environment').selectOption('static')
  await expect(page.getByText('Create and assign a generator pool', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Capacity commitments' })).toBeVisible()
  await page.goto(`/#/settings?setting=grafana&${scopeQuery(workspace)}`)
  const url = page.getByRole('textbox', { name: 'Grafana server URL' })
  const original = await url.inputValue()
  await url.fill('https://pending.example.test')
  await expect(page.getByRole('region', { name: 'Pending deployment edits' })).toContainText('grafana')
  const cancel = page.getByRole('button', { name: 'Cancel deployment changes', exact: true })
  await cancel.focus(); await page.keyboard.press('Enter')
  await expect(url).toHaveValue(original)
  await expect(page.getByRole('region', { name: 'Pending deployment edits' })).toHaveCount(0)
})
