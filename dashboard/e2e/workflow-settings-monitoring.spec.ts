import { test, expect, login } from './support/workflow'
import { createWorkspace, scopeQuery } from './support/workspace'

test.beforeEach(async ({ page }) => {
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
})

for (const width of [1024, 1280, 1440]) {
  test(`Settings navigation and canonical editors at ${width}px`, async ({ page }) => {
    const workspace = await createWorkspace(page.context().request)
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(`/#/settings?setting=grafana&${scopeQuery(workspace)}`)
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Grafana', exact: true })).toBeVisible()
    await expect(page.getByText('Applies to: Entire deployment', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: /Reset.*Defaults/ })).toBeHidden()
    const browse = page.getByRole('button', { name: 'Expand Settings navigation' })
    if (await browse.isVisible()) await browse.click()
    await page.getByRole('searchbox', { name: 'Find settings' }).fill('OpenSearch')
    await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'OpenSearch', exact: true }).click()
    await expect(page).toHaveURL(/setting=opensearch/)
    await expect(page.getByRole('heading', { name: 'OpenSearch', exact: true })).toBeVisible()
    await page.goBack()
    await expect(page.getByRole('heading', { name: 'Grafana', exact: true })).toBeVisible()
    expect(new URLSearchParams(new URL(page.url()).hash.split('?')[1]).get('projectId')).toBe(workspace.projectId)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.goto(`/#/settings?setting=pools&${scopeQuery(workspace)}`)
    await page.getByRole('button', { name: 'New Pool', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'New Pool', exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByText('Advanced lifecycle & admission policy', { exact: true })).toBeVisible()
    expect(await dialog.evaluate(element => {
      const heading = element.querySelector('h3')!
      const rect = heading.getBoundingClientRect()
      return element.contains(document.elementFromPoint(rect.left + 2, rect.top + rect.height / 2)) && getComputedStyle(element).backgroundColor !== 'rgba(0, 0, 0, 0)'
    })).toBe(true)
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.goto(`/#/monitoring?category=alerts&${scopeQuery(workspace)}`)
    await expect(page.getByRole('tab', { name: /Alerts/ })).toHaveAttribute('aria-selected', 'true')
    await page.getByRole('link', { name: 'Notification routes', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Notification routes', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Return to originating workflow', exact: true }).click()
    await expect(page.getByRole('tab', { name: /Alerts/ })).toHaveAttribute('aria-selected', 'true')
    await page.goto(`/#/access?setting=redaction&${scopeQuery(workspace)}`)
    await page.getByText('Validate rules and preview redaction', { exact: true }).click()
    await page.getByRole('button', { name: 'Validate and preview', exact: true }).click()
    await expect(page.getByLabel('Redacted sample', { exact: true })).toContainText('[REDACTED]')
  })
}

test('settings destination navigation preserves unsaved edits until explicitly discarded', async ({ page }) => {
  const workspace = await createWorkspace(page.context().request)
  await page.goto(`/#/settings?setting=grafana&${scopeQuery(workspace)}`)
  await page.reload()
  await page.getByRole('textbox', { name: 'Grafana server URL' }).fill('https://draft.example.test')
  await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'APEX platform graphs', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Grafana server URL' })).toHaveValue('https://draft.example.test')
  await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'APEX platform graphs', exact: true }).click()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'APEX platform graphs', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('textbox', { name: 'Grafana server URL' })).not.toHaveValue('https://draft.example.test')
})

test('infrastructure guide, saved commitments and independent cancel work with keyboard navigation', async ({ page }) => {
  const workspace = await createWorkspace(page.context().request)
  await page.goto(`/#/settings?setting=allocations&${scopeQuery(workspace)}`)
  await page.reload()
  await page.getByText('Infrastructure setup guide', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Execution environment')).toBeVisible()
  await page.getByLabel('Execution environment').selectOption('static')
  await expect(page.getByText('Create and assign a generator pool', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Capacity commitments' })).toBeVisible()
  await page.goto(`/#/settings?setting=grafana&${scopeQuery(workspace)}`)
  const url = page.getByRole('textbox', { name: 'Grafana server URL' })
  const original = await url.inputValue()
  await url.fill('https://pending.example.test')
  await expect(page.getByRole('region', { name: 'Pending deployment edits' })).toContainText('grafana')
  const cancel = page.getByRole('button', { name: 'Cancel deployment changes', exact: true })
  await cancel.focus(); await page.keyboard.press('Enter')
  await expect(url).toHaveValue(original)
  await expect(page.getByRole('region', { name: 'Pending deployment edits' })).toHaveCount(0)
})


test('project catalog edits, cancels and confirms deletion against persisted workspace data', async ({ page }) => {
  const workspace = await createWorkspace(page.context().request)
  await page.goto(`/#/settings?setting=projects&${scopeQuery(workspace)}`)
  await page.reload()
  const editor = page.getByRole('region', { name: 'Edit selected project' })
  const name = editor.getByRole('textbox', { name: 'Edit project name' })
  const original = await name.inputValue()
  await editor.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(name).toBeFocused()
  await name.fill('Unsaved rename')
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(name).toHaveValue(original)
  const renamed = `${original} renamed`
  await name.fill(renamed)
  const saved = page.waitForResponse(response => response.url().includes(`/projects/${workspace.projectId}`) && response.request().method() === 'PUT')
  await editor.getByRole('button', { name: 'Save', exact: true }).click()
  expect((await saved).ok()).toBe(true)
  await page.reload()
  await expect(name).toHaveValue(renamed)
  await editor.getByRole('button', { name: 'Delete', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Delete Project', exact: true })
  await expect(dialog).toContainText(renamed)
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(name).toHaveValue(renamed)
  await editor.getByRole('button', { name: 'Delete', exact: true }).click()
  const deleted = page.waitForResponse(response => response.url().includes(`/projects/${workspace.projectId}`) && response.request().method() === 'DELETE')
  await dialog.getByRole('button', { name: 'Delete Project', exact: true }).click()
  expect((await deleted).ok()).toBe(true)
  await expect(dialog).toBeHidden()
  const response = await page.context().request.get(`/api/v1/projects?domain_id=${workspace.domainId}`)
  expect(response.ok()).toBe(true)
  expect((await response.json()).projects.map((project: { id: string }) => project.id)).not.toContain(workspace.projectId)
})

test('Settings search reveals and focuses each matching personal control', async ({ page }) => {
  const workspace = await createWorkspace(page.context().request)
  await page.setViewportSize({ width: 923, height: 1000 })
  await page.goto(`/#/settings?setting=projects&${scopeQuery(workspace)}`)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()
  for (const [query, label] of [['dark', 'Dashboard Theme'], ['word wrap', 'Editor word wrap'], ['rows', 'Default rows per table'], ['motion', 'Motion']]) {
    const expand = page.getByRole('button', { name: 'Expand Settings navigation' })
    if (await expand.isVisible()) await expand.click()
    await page.getByRole('searchbox', { name: 'Find settings' }).fill(query)
    await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'Personal preferences', exact: true }).click()
    const control = page.getByRole('combobox', { name: label, exact: true })
    await expect(control).toBeFocused()
    await expect(control).toBeInViewport()
  }
  await page.goto(`/#/access?setting=authentication&${scopeQuery(workspace)}`)
  await expect(page.getByRole('heading', { name: 'Authentication', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Access administration' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Settings sections' })).toBeHidden()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  const expandSettings = page.getByRole('button', { name: 'Expand Settings navigation' })
  if (await expandSettings.isVisible()) await expandSettings.click()
  await page.getByRole('searchbox', { name: 'Find settings' }).fill('theme')
  await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'Personal preferences', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Dashboard Theme', exact: true })).toBeFocused()
})
