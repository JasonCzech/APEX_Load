import path from 'node:path'
import { test, expect, mutation, json, login } from './support/workflow'
import { createWorkspace, scopeQuery } from './support/workspace'

test('reviews and saves nested VuGen projects independently, retaining failed and Java reviews', async ({ page }) => {
  // Login, workspace setup, independent reviews, and the atomic save form one full workflow.
  test.slow()
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await login(page)
  const workspace = await createWorkspace(page.context().request)
  await page.goto(`/#/scripts?mode=create&${scopeQuery(workspace)}`)
  if (process.env.APEXLOAD_E2E_PROFILE === 'local-auth') await page.reload()
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  await page.getByRole('button', { name: /Import Loadrunner Script Archive/ }).click()
  await page.locator('input[type=file][accept=".zip,.usz"]').setInputFiles(path.join(process.cwd(), 'e2e/fixtures/loadrunner-collection.zip'))
  await page.getByRole('button', { name: 'Validate Script(s)', exact: true }).click()
  const queue = page.getByLabel('Queued enterprise script archives')
  await expect(queue.locator('.lr-file-row')).toHaveCount(3)
  await expect(queue).toContainText('from loadrunner-collection.zip')
  await expect(queue.locator('.lr-file-row.failed')).toContainText('Broken.USZ')
  await page.getByRole('combobox', { name: 'Review imported project', exact: true }).selectOption({ label: 'JavaDemo.USZ — Needs runner / approval' })
  await expect(page.getByText('Needs runner / approval', { exact: true }).first()).toBeVisible()
  await page.getByRole('combobox', { name: 'Review imported project', exact: true }).selectOption({ label: 'WebDemo.USZ — Ready to save' })
  await page.getByRole('tab', { name: 'Runtime settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Runtime settings', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Review', exact: true }).click()
  const setup = page.locator('.lr-completed-setup')
  await setup.locator(':scope > summary').click()
  const saved = mutation(page, 'POST', '/api/v1/scripts/import/enterprise-script-archive/save')
  await page.locator('.lr-import-actions-card').getByRole('button', { name: 'Save reviewed drafts', exact: true }).click()
  const receipt = await json(await saved)
  expect(receipt.scripts).toHaveLength(1)
  await expect(page.getByRole('button', { name: 'Import More Files', exact: true })).toBeVisible()
  await expect(queue.locator('.lr-file-row')).toHaveCount(3)
  await expect(queue.locator('.lr-file-row.failed')).toContainText('Broken.USZ')
  await queue.getByRole('button', { name: /^WebDemo\.USZ / }).click()
  await expect(page.getByRole('tab', { name: 'Source Mapping', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Review imported project', exact: true }).selectOption({ label: 'JavaDemo.USZ — Needs runner / approval' })
  const reviewSaved = mutation(page, 'POST', '/api/v1/scripts/authoring/sessions')
  await page.getByRole('button', { name: /^Save (Combined Java Draft for Approval|Review Artifact Instead)$/ }).click()
  const reviewReceipt = await json(await reviewSaved)
  expect(reviewReceipt.id).toBeTruthy()
  await expect(page.getByText(/saved as authoring session/)).toBeVisible()
  await expect(page.getByText(/1 script saved · 1 review session saved · 0 drafts awaiting save/)).toBeVisible()
  await expect(page.getByText('Execution blocked', { exact: true }).first()).toBeVisible()
})
