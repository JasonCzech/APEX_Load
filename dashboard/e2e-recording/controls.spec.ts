import { test, expect } from './support/fixtures'
import { studio, startRecording, stopRecording, snapshot, preview, verifyOutputs, Toolbar } from './support/journey'

test('dashboard and closed-shadow toolbar control the same live session', async ({ page, harness: h }, info) => {
  await studio(page,h)
  const rec = await startRecording(page,h,false,{ screenshots:true })
  const bar = await Toolbar.for(rec.target)
  try {
    await expect.poll(()=>rec.browser.contexts().flatMap(context=>context.pages()).some(tab=>tab.url().includes(`#/recorder-panel?session=${rec.id}`))).toBe(true)
    const companion=rec.browser.contexts().flatMap(context=>context.pages()).find(tab=>tab.url().includes(`#/recorder-panel?session=${rec.id}`))!
    if(info.project.name==='local-auth') {
      await companion.getByLabel('Username',{exact:true}).fill('admin')
      await companion.getByLabel('Password',{exact:true}).fill('admin')
      await companion.getByRole('button',{name:'Sign in',exact:true}).click()
      for(const cookie of await companion.context().cookies()) h.target.sensitiveValues.add(cookie.value)
    }
    await expect(companion.getByTestId('browser-recorder-panel')).toBeVisible()
    await companion.getByRole('button',{name:'Pause recording',exact:true}).click()
    await page.getByRole('button',{name:'Resume recording',exact:true}).click()
    await page.getByRole('button',{name:'Focus browser',exact:true}).click()
    await page.getByRole('button',{name:'Pause recording',exact:true}).click()
    await rec.target.getByLabel('Customer',{exact:true}).fill('must-not-be-recorded')
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    const paused = await snapshot(h,rec.id)
    expect(paused.status).toBe('paused')
    expect(JSON.stringify(paused.steps)).not.toContain('must-not-be-recorded')
    await bar.click('.panel .pause')
    await expect(page.getByRole('button',{name:'Pause recording',exact:true})).toBeVisible()
    await bar.click('.panel .pause')
    await expect(page.getByRole('button',{name:'Resume recording',exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Resume recording',exact:true}).click()
    await bar.click('[data-section="init"]')
    await expect.poll(async()=> (await snapshot(h,rec.id)).section).toBe('init')
    await rec.target.getByLabel('Customer',{exact:true}).fill('init-value')
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await expect.poll(async()=> (await snapshot(h,rec.id)).steps.length).toBe(2)
    await page.getByTestId('section-actions').click()
    await page.getByLabel('Transaction name',{exact:true}).fill('Main journey')
    await page.getByRole('button',{name:'Start transaction',exact:true}).click()
    await page.getByLabel('Note',{exact:true}).fill('A real recorded event')
    await page.getByRole('button',{name:'Add note',exact:true}).click()
    await rec.target.getByLabel('Customer',{exact:true}).fill('main-value')
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await expect.poll(async()=> (await snapshot(h,rec.id)).steps.length).toBeGreaterThan(3)
    await page.getByRole('button',{name:'End transaction Main journey',exact:true}).click()
    const kept=(await snapshot(h,rec.id)).steps.length
    await page.getByTitle('Exclude',{exact:true}).first().click()
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{excluded?:boolean})=>s.excluded)).toBe(true)
    await page.getByTitle('Include',{exact:true}).first().click()
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{excluded?:boolean})=>s.excluded)).toBe(false)
    await expect.poll(()=>bar.count('[title="Include step"]')).toBe(0)
    await bar.click('.stepsList [title="Exclude step"]')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{excluded?:boolean})=>s.excluded)).toBe(true)
    await expect.poll(()=>bar.count('[title="Include step"]')).toBe(1)
    await bar.click('.stepsList [title="Include step"]')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{excluded?:boolean})=>s.excluded)).toBe(false)
    await rec.target.getByLabel('Customer',{exact:true}).fill('temporary-marking-value')
    await rec.target.getByLabel('Customer',{exact:true}).press('Tab')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.filter((s:{kind:string})=>s.kind==='fill').length).toBe(3)
    await page.getByTitle('Mark as data parameter',{exact:true}).last().click()
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{mark_param:boolean})=>s.mark_param)).toBe(true)
    await page.getByTitle('Mark as secret',{exact:true}).last().click()
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{mark_secret:boolean})=>s.mark_secret)).toBe(true)
    await expect.poll(()=>bar.count('[title="Mark as secret"].on')).toBe(1)
    await bar.click('[title="Mark as secret"].on')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{mark_secret:boolean})=>s.mark_secret)).toBe(false)
    await expect.poll(()=>bar.count('[title="Mark as secret"].on')).toBe(0)
    await bar.click('.step:has([title="Mark as parameter"].on) [title="Mark as secret"]')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{mark_secret:boolean})=>s.mark_secret)).toBe(true)
    await expect.poll(()=>bar.count('[title="Mark as secret"].on')).toBe(1)
    await bar.click('[title="Mark as parameter"].on')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{mark_param:boolean})=>s.mark_param)).toBe(false)
    await expect.poll(()=>bar.count('[title="Mark as parameter"].on')).toBe(0)
    await bar.click('.step:has([title="Mark as secret"].on) [title="Mark as parameter"]')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{mark_param:boolean})=>s.mark_param)).toBe(true)
    // Delete the sacrificial key/fill after checking their metadata; the final
    // output retains the executable main journey and needs no hidden secrets.
    while((await snapshot(h,rec.id)).steps.length>kept) {
      const count=(await snapshot(h,rec.id)).steps.length
      await page.getByRole('button',{name:'Delete last step',exact:true}).click()
      await expect.poll(async()=>(await snapshot(h,rec.id)).steps.length).toBe(count-1)
    }
    // The API acknowledges deletion before the recorder's pushed sidebar
    // snapshot arrives. Wait for that visible update: removing a row moves
    // every control in the bottom-anchored dock.
    await expect.poll(()=>bar.count('.stepsList .step')).toBe(kept)

    await bar.fill('.noteText','Sidebar note')
    await bar.click('.noteAdd')
    await expect.poll(async()=>(await snapshot(h,rec.id)).markers.some((marker:{text:string})=>marker.text==='Sidebar note')).toBe(true)
    await expect.poll(()=>bar.count('.txnName:not([disabled])')).toBe(1)
    await bar.fill('.txnName','Sidebar transaction')
    await bar.click('.txnToggle')
    await expect.poll(async()=>(await snapshot(h,rec.id)).markers.some((marker:{kind:string;name:string})=>marker.kind==='transaction_start'&&marker.name==='Sidebar transaction')).toBe(true)
    await expect.poll(()=>bar.count('.txnToggle.stop')).toBe(1)
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await expect.poll(()=>bar.count('.stepsList .step')).toBe(kept+1)
    await bar.click('.txnToggle')
    await expect.poll(async()=>(await snapshot(h,rec.id)).markers.some((marker:{kind:string;name:string})=>marker.kind==='transaction_end'&&marker.name==='Sidebar transaction')).toBe(true)
    await expect.poll(()=>bar.count('.txnToggle.stop')).toBe(0)
    const before = (await snapshot(h,rec.id)).steps.length
    await rec.target.getByRole('button',{name:'Double action',exact:true}).click()
    await expect.poll(async()=> (await snapshot(h,rec.id)).steps.length).toBe(before+1)
    await expect.poll(()=>bar.count('.stepsList .step')).toBe(before+1)
    await bar.click('.undo')
    await expect.poll(async()=> (await snapshot(h,rec.id)).steps.length).toBe(before)
    await expect.poll(()=>bar.count('.stepsList .step')).toBe(before)
    await bar.click('.panel .assert')
    await expect(page.getByTestId('pick-mode-toggle')).toContainText('Picking')
    await rec.target.locator('#result').click()
    await expect(page.getByTestId('pick-mode-toggle')).toHaveText('Pick verification')
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.some((s:{kind:string})=>s.kind==='assert')).toBe(true)
    await bar.click('.collapse')
    await bar.click('.expand')
    const head = await bar.point('.phead')
    await rec.target.mouse.move(head.x,head.y); await rec.target.mouse.down(); await rec.target.mouse.move(50,100,{steps:8}); await rec.target.mouse.up()
    await expect.poll(async()=>rec.target.evaluate(()=>localStorage.getItem('apexload_rec_sidebar_corner'))).toBe('tl')
    await page.getByTestId('section-teardown').click()
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await page.getByTestId('section-actions').click()
    await page.getByLabel('Navigate URL scheme').selectOption('http://')
    await page.getByLabel('Navigate the recording browser').fill(h.target.url.replace('http://','')+'/?again=1')
    await page.getByTestId('browser-recorder-panel').getByRole('button',{name:'Go',exact:true}).click()
    await expect(rec.target).toHaveURL(/again=1/)
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await expect(page.getByTestId('transaction-suggestions')).toBeVisible()
    await page.getByTestId('transaction-suggestions').getByRole('button',{name:'Add',exact:true}).first().click()
    await bar.fill('.navUrl',h.target.url+'/?toolbar=1')
    await bar.click('.navGo')
    await expect(rec.target).toHaveURL(/toolbar=1/)
    await page.reload()
    await page.getByRole('button',{name:'Script Builder',exact:true}).click()
    await page.getByRole('button',{name:'Record',exact:true}).click()
    await expect(page.getByRole('button',{name:'Pause recording',exact:true})).toBeVisible()
    await stopRecording(page)
    const captured = await snapshot(h,rec.id)
    expect(captured.steps.map((s:{section:string})=>s.section)).toEqual(expect.arrayContaining(['init','actions','teardown']))
    expect(JSON.stringify(captured.markers)).toContain('Main journey')
    expect(JSON.stringify(captured.markers)).toContain('Sidebar transaction')
    expect(JSON.stringify(captured.markers)).toContain('A real recorded event')
    expect(JSON.stringify(captured.markers)).toContain('Sidebar note')
    expect(captured.steps.every((s:{element?:{id?:string}})=>!s.element?.id || ['customer','event','double','result'].includes(s.element.id))).toBe(true)
    await page.getByRole('button',{name:'Load thumbnails',exact:true}).click()
    await expect(page.locator('.brp-step-thumbnail').first()).toBeVisible()
    expect(JSON.stringify(captured)).not.toContain('must-not-be-recorded')
    await info.attach('recorded-session',{body:JSON.stringify(captured,null,2),contentType:'application/json'})
    const download = page.waitForEvent('download')
    await page.getByRole('button',{name:'Download HAR',exact:true}).click()
    const harDownload = await download
    expect(await harDownload.failure()).toBeNull()
    await info.attach('recording.har', {path:(await harDownload.path())!,contentType:'application/json'})
    await preview(page,info)
    await verifyOutputs(page,1)
  } finally { await bar.close(); await rec.browser.close().catch(()=>{}) }
})

test('capture modern web surfaces and preserve conversion warnings', async ({ page, harness:h },info)=>{
  await studio(page,h)
  const rec=await startRecording(page,h,false,{ws:true})
  try {
    const target=rec.target
    await target.getByLabel('Customer',{exact:true}).fill('keyboard-customer')
    await target.getByLabel('Customer',{exact:true}).press('Tab')
    await target.getByLabel('Password',{exact:true}).fill('synthetic-password')
    await target.getByRole('option',{name:'Premium',exact:true}).click()
    await expect(target.getByLabel('Plan',{exact:true})).toHaveValue('premium')
    await target.getByLabel('Agree',{exact:true}).check()
    await target.getByLabel('Choice',{exact:true}).check()
    await target.getByRole('button',{name:'Double action',exact:true}).dblclick()
    await target.getByRole('button',{name:'Hover action',exact:true}).hover()
    await expect.poll(async()=> (await snapshot(h,rec.id)).steps.some((s:{kind:string})=>s.kind==='hover')).toBe(true)
    await target.locator('#drag').dragTo(target.locator('#drop'))
    const {writeFile}=await import('node:fs/promises')
    await writeFile(`${h.dir}/upload.txt`,'synthetic upload')
    const inputCDP=await target.context().newCDPSession(target)
    const {root}=await inputCDP.send('DOM.getDocument')
    const {nodeId}=await inputCDP.send('DOM.querySelector',{nodeId:root.nodeId,selector:'#file'})
    await inputCDP.send('DOM.setFileInputFiles',{nodeId,files:[`${h.dir}/upload.txt`]})
    await inputCDP.detach()
    await target.frameLocator('#frame').getByRole('button',{name:'Frame action'}).click()
    await target.locator('#shadow').getByRole('button',{name:'Shadow action'}).click()
    await target.getByRole('button',{name:'Dialog action',exact:true}).click()
    const popupPromise=target.waitForEvent('popup')
    await target.getByRole('button',{name:'Open popup',exact:true}).click()
    const popup=await popupPromise
    await popup.getByRole('button',{name:'Popup action'}).click()
    await target.bringToFront()
    await target.getByRole('button',{name:'SPA route',exact:true}).click()
    await target.getByRole('button',{name:'Open socket',exact:true}).click()
    await expect(target.locator('#ws-result')).toHaveText('fixture-ready')
    await target.getByRole('button',{name:'Bottom action',exact:true}).scrollIntoViewIfNeeded()
    await target.getByRole('button',{name:'Bottom action',exact:true}).click()
    await expect.poll(async()=> (await snapshot(h,rec.id)).steps.some((s:{kind:string})=>s.kind==='scroll')).toBe(true)
    await stopRecording(page)
    const captured=await snapshot(h,rec.id,true)
    const kinds=captured.steps.map((s:{kind:string})=>s.kind)
    expect(kinds).toEqual(expect.arrayContaining(['fill','press_key','select','click','dblclick','hover','drag_and_drop','set_files','handle_dialog','switch_window','scroll']))
    expect(captured.websocket_count).toBeGreaterThan(0)
    expect(JSON.stringify(captured)).not.toContain('synthetic-password')
    const converted=await preview(page,info)
    const socketWaits=converted.script.actions.filter((a:{type:string})=>a.type==='browser_ws_wait')
    expect(socketWaits).toHaveLength(2)
    expect(socketWaits[0].params.match).toContain('fixture-ready')
    expect(socketWaits[1].params.direction).toBe('received')
    expect(socketWaits[1].params.match).toBeUndefined() // A redacted payload must not become a runtime matcher.
    expect(JSON.stringify(socketWaits)).not.toContain('fixture-ws-secret')
    expect(converted.warnings?.join(' ')).toMatch(/upload|fixture paths/i)
    expect(converted.warnings?.join(' ')).toMatch(/password|masked/i)
    expect(converted.script.actions.find((a:{type:string})=>a.type==='browser_set_files')?.value).toBe('upload.txt')
    expect(converted.script.actions.find((a:{selector:string})=>a.selector==='#password')?.value).toBe('{{env.PASSWORD}}')
    expect(captured.steps.find((s:{element?:{id:string}})=>s.element?.id==='frame-action')?.frame_selector).toBeTruthy()
    expect(captured.steps.find((s:{element?:{id:string}})=>s.element?.id==='shadow-action')?.candidates.length).toBeGreaterThan(0)
    await info.attach('capture-surfaces',{body:JSON.stringify(captured,null,2),contentType:'application/json'})
  } finally { await rec.browser.close().catch(()=>{}) }
})
