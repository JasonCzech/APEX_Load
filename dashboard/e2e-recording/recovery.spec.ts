import {test,expect} from './support/fixtures'
import {studio,startRecording,stopRecording,snapshot,preview,verifyOutputs,Toolbar} from './support/journey'

test('reject duplicate capture, survive dashboard reload and recover after window closure',async({page,harness:h},info)=>{
  await studio(page,h)
  await page.getByLabel('Start URL address',{exact:true}).fill('file:///etc/passwd')
  await page.getByRole('button',{name:'Start browser recording',exact:true}).click()
  await expect(page.getByLabel('Start URL address',{exact:true})).toHaveAttribute('aria-invalid','true')
  const rec=await startRecording(page,h)
  try{
    const duplicate=await h.request.post('/api/v1/browser-recorder/sessions',{data:{project_id:h.workspace.projectId,start_url:h.target.url}})
    expect(duplicate.status()).toBe(409)
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.length).toBeGreaterThan(0)
    await page.reload()
    // Studio selection is an internal authoring state; recover via the visible
    // recording entry when reloading the library route.
    await page.getByRole('button',{name:'Script Builder',exact:true}).click()
    await page.getByRole('button',{name:'Record',exact:true}).click()
    await expect(page.getByRole('button',{name:'Stop Recording',exact:true})).toBeVisible()
    await rec.target.close()
    await expect.poll(async()=>(await snapshot(h,rec.id)).status,{timeout:30_000}).toBe('stopped')
    const stopped=await snapshot(h,rec.id)
    expect(stopped.stop_reason).toBe('browser_closed')
    expect(stopped.steps.length).toBeGreaterThan(0)
    await preview(page,info)
    await verifyOutputs(page,1)
    await studio(page,h)
    const next=await startRecording(page,h,false,{har:false,minimal:true})
    const toolbar=await Toolbar.for(next.target)
    await toolbar.click('.bar .stopRec')
    await expect.poll(async()=>(await snapshot(h,next.id)).status,{timeout:30_000}).toBe('stopped')
    expect((await snapshot(h,next.id)).har_available).toBe(false)
    await toolbar.close();await next.browser.close().catch(()=>{})
  }finally{await rec.browser.close().catch(()=>{})}
})

test('mobile recording reuses exported session state with HAR disabled',async({page,harness:h},info)=>{
  await studio(page,h)
  const preset=page.getByLabel('Emulated device preset',{exact:true})
  await expect(preset.locator('option').filter({hasText:'iphone 15 pro'})).toHaveCount(1)
  const mobileValue=await preset.locator('option').evaluateAll(options=>(options.find(o=>/iphone|pixel/i.test(o.textContent||'')) as HTMLOptionElement|undefined)?.value)
  expect(mobileValue).toBeTruthy()
  await preset.selectOption(mobileValue!)
  const rec=await startRecording(page,h,false,{har:false,minimal:true})
  try{
    expect(await rec.target.evaluate(()=>navigator.maxTouchPoints)).toBeGreaterThan(0)
    await expect(rec.target.locator('#stored-state')).toHaveText('empty')
    await rec.target.getByRole('button',{name:'Remember session',exact:true}).click()
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await stopRecording(page)
    const captured=await snapshot(h,rec.id)
    expect(captured.device_profile).toBeTruthy();expect(captured.har_available).toBe(false)
    const state=await h.request.get(`/api/v1/browser-recorder/sessions/${rec.id}/storage-state`)
    expect(state.ok(),await state.text()).toBeTruthy()
    await info.attach('session-storage-state', {body:await state.text(),contentType:'application/json'})
    const statePath=state.headers()['x-apexload-storagestate-path'];expect(statePath).toBeTruthy()
    await preview(page,info)
    await verifyOutputs(page,1)
    await studio(page,h)
    await page.getByRole('button',{name:'Advanced options',exact:true}).click()
    await page.getByLabel('Reuse session state path',{exact:true}).fill(statePath)
    const next=await startRecording(page,h,false,{har:false})
    await expect(next.target.locator('#stored-state')).toHaveText('remembered-by-recording')
    await stopRecording(page)
    await next.browser.close().catch(()=>{})
  }finally{await rec.browser.close().catch(()=>{})}
})

test('force-finish preserves captured steps and releases a stuck recording for the next session',async({page,harness:h},info)=>{
  const {writeFile,rm}=await import('node:fs/promises')
  await studio(page,h)
  const rec=await startRecording(page,h)
  try{
    await rec.target.getByRole('button',{name:'Record event',exact:true}).click()
    await expect.poll(async()=>(await snapshot(h,rec.id)).steps.length).toBeGreaterThan(0)
    await writeFile(`${h.dir}/stop-gate`,'hold')
    await page.getByRole('button',{name:'Stop Recording',exact:true}).click()
    await expect(page.getByRole('button',{name:'Force Finish',exact:true})).toBeEnabled({timeout:25_000})
    await page.getByRole('button',{name:'Force Finish',exact:true}).click()
    await expect.poll(async()=>(await snapshot(h,rec.id)).status).toBe('stopped')
    expect((await snapshot(h,rec.id)).steps.length).toBeGreaterThan(0)
    await rm(`${h.dir}/stop-gate`)
    await preview(page,info);await verifyOutputs(page,1)
    await studio(page,h)
    const next=await startRecording(page,h,false,{har:false})
    await stopRecording(page)
    await next.browser.close().catch(()=>{})
  }finally{await rec.browser.close().catch(()=>{})}
})
