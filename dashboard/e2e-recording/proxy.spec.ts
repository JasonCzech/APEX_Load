import { chromium } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { test, expect } from './support/fixtures'
import { studio, editor, executeSaved, editSource, debug } from './support/journey'

test('HTTP proxy captures HTTP and HTTPS, edits requests, correlates and replays', async ({page,harness:h},info)=>{
  test.setTimeout(300_000)
  await studio(page,h)
  await page.getByRole('button',{name:'HTTP proxy (advanced)',exact:true}).click()
  await page.getByPlaceholder('e.g. Login & Checkout Flow').fill('Proxy checkout')
  await page.getByPlaceholder('e.g. api.example.com, app.example.com').fill('127.0.0.1')
  await page.getByPlaceholder('e.g. analytics.google.com, cdn.example.com').fill('localhost')
  const started=page.waitForResponse(r=>r.url().endsWith('/recorder/start'))
  await page.getByRole('button',{name:'Start Recording',exact:true}).click()
  const response=await started; expect(response.ok(),await response.text()).toBeTruthy()
  const {session,proxy_addr:proxy}=await response.json()
  h.ownedPorts.push(Number(new URL(`http://${proxy}`).port))
  expect(session.project_id).toBe(h.workspace.projectId)
  const browser=await chromium.launch({headless:false,proxy:{server:`http://${proxy}`},args:['--proxy-bypass-list=<-loopback>']})
  const context=await browser.newContext({ignoreHTTPSErrors:true}) // Trust is confined to this synthetic client, never the OS.
  const target=await context.newPage()
  try {
    await target.goto(h.target.url+'/redirect')
    await expect(target.locator('body')).toHaveAttribute('data-token',/.+/)
    await target.getByLabel('Customer',{exact:true}).fill('proxy-customer')
    await target.getByRole('button',{name:'Checkout',exact:true}).click()
    await expect(target.locator('#result')).toHaveText('Order accepted')
    await target.getByRole('button',{name:'Excluded host event',exact:true}).click()
    await expect.poll(()=>h.target.events.some(e=>e.query.name==='filtered')).toBe(true)
    await target.getByRole('button',{name:'Submit form',exact:true}).click()
    await expect.poll(()=>h.target.events.some(e=>e.body==='form_value=form-customer')).toBe(true)
    await page.getByRole('button',{name:'Pause Recording',exact:true}).click()
    await target.goto(h.target.url+'/event?name=paused')
    await page.getByRole('button',{name:'Resume Recording',exact:true}).click()
    await target.goto(h.target.httpsURL+'/event?name=https')
    await page.getByRole('button',{name:'Stop Recording',exact:true}).click()
    await expect(page.getByRole('button',{name:'Select recording session Proxy checkout',exact:true})).toBeVisible()
    const stored=await h.request.get(`/api/v1/recorder/${session.id}?include=requests`)
    expect(stored.ok()).toBeTruthy()
    const captured=await stored.json()
    await info.attach('proxy-recording', {body:JSON.stringify(captured,null,2),contentType:'application/json'})
    expect(captured.requests.some((r:{url:string})=>r.url.includes('name=paused'))).toBe(false)
    expect(captured.requests.some((r:{url:string})=>r.url.includes('noise.css'))).toBe(false)
    expect(captured.requests.some((r:{url:string})=>r.url.includes('name=filtered'))).toBe(false)
    expect(captured.requests.some((r:{body:string})=>r.body==='form_value=form-customer')).toBe(true)
    expect(captured.requests.some((r:{url:string})=>r.url.startsWith(h.target.httpsURL))).toBe(true)
    await page.getByRole('button',{name:'Select recording session Proxy checkout',exact:true}).click()
    const https=captured.requests.find((r:{url:string})=>r.url.includes('name=https'))
    await page.getByRole('button',{name:`Select request ${https.seq}`,exact:true}).click()
    await page.getByLabel('Step Name',{exact:true}).fill('HTTPS diagnostic')
    await page.getByLabel('Transaction',{exact:true}).fill('Network capture')
    await page.getByLabel('Think Time (ms)',{exact:true}).fill('5')
    await page.getByLabel('Note',{exact:true}).fill('Exclude diagnostic from checkout replay')
    await page.getByLabel('Use in generated script',{exact:true}).uncheck()
    const editedRequest=page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url().endsWith(`/recorder/${session.id}/requests/${https.seq}`))
    await page.getByRole('button',{name:'Save Request',exact:true}).click()
    const editedResponse=await editedRequest
    expect(editedResponse.ok(),await editedResponse.text()).toBeTruthy()
    const edited=await editedResponse.json()
    expect(edited).toMatchObject({step_name:'HTTPS diagnostic',transaction_name:'Network capture',think_time_ms:5,note:'Exclude diagnostic from checkout replay',excluded:true})
    await info.attach('edited-proxy-request',{body:JSON.stringify(edited,null,2),contentType:'application/json'})
    const downloadPromise=page.waitForEvent('download')
    await page.getByRole('button',{name:'Export HAR',exact:true}).click()
    const har=JSON.parse(await readFile((await (await downloadPromise).path())!,'utf8'))
    expect(har.log.entries.length).toBeGreaterThan(0)
    await info.attach('proxy.har', {body:JSON.stringify(har,null,2),contentType:'application/json'})
    const reviewed=page.waitForResponse(r=>r.url().endsWith(`/recorder/${session.id}/convert/preview`))
    await page.getByRole('button',{name:'Convert to script',exact:true}).click()
    const convertedResponse=await reviewed; expect(convertedResponse.ok(),await convertedResponse.text()).toBeTruthy()
    const converted=await convertedResponse.json()
    expect(converted.script.protocol).toBe('http')
    expect(JSON.stringify(converted.script)).not.toContain('name=https')
    expect(converted.correlations.find((c:{expression:string})=>c.expression==='$.csrf_token')?.pre_applied).toBe(true)
    expect(converted.correlations.find((c:{expression:string})=>c.expression==='$.order_id')?.review_action).toBe('manual_review_required')
    await info.attach('proxy-conversion',{body:JSON.stringify(converted,null,2),contentType:'application/json'})
    const saved=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/scripts/import/commit-batch'))
    await page.getByRole('button',{name:'Save to script library',exact:true}).click()
    const savedResponse=await saved; expect(savedResponse.ok(),await savedResponse.text()).toBeTruthy()
    const payload=await savedResponse.json()
    const id=payload.scripts?.[0]?.id||payload.stored_script?.id||payload.script_id||payload.id
    expect(id).toBeTruthy()
    h.target.rotateTokens()
    await editor(page,h,id)
    // Generic IDs deliberately require review below the automatic confidence
    // threshold. Prepare that warned dependency through the editor; CSRF stays
    // the converter's automatically applied extraction/substitution.
    const savedScript=await h.request.get(`/api/v1/scripts/${id}`)
    const script=(await savedScript.json()).script
    const token=script.actions.find((a:{target:string})=>a.target==='/token')
    token.extractors=[...(token.extractors||[]),{name:'manual_order_id',source:'body',type:'jsonpath',expression:'$.order_id'}]
    const checkout=script.actions.find((a:{target:string})=>a.target==='/checkout')
    checkout.body=JSON.stringify({...JSON.parse(checkout.body),order_id:'{{var.manual_order_id}}'})
    await editSource(page,script)
    await debug(page,info)
    expect(h.target.events.filter(e=>e.path==='/checkout'&&e.accepted)).toHaveLength(2)
    await executeSaved(page,h,id,info)
    const orders=h.target.events.filter(e=>e.path==='/checkout').map(e=>JSON.parse(e.body))
    expect(new Set(orders.map(o=>o.csrf_token)).size).toBe(3)
    expect(new Set(orders.map(o=>o.order_id)).size).toBe(3)
    await studio(page,h)
    // Recent recordings lists both methods' recordings; delete this one's.
    const proxyRecording=page.getByTestId('recent-recordings').locator('.rec-session-card').filter({has:page.getByRole('button',{name:'Select recording session Proxy checkout',exact:true})})
    await proxyRecording.getByRole('button',{name:'Delete',exact:true}).click()
    await page.getByRole('alertdialog').getByRole('button',{name:'Delete',exact:true}).click()
    await expect(page.getByRole('button',{name:'Select recording session Proxy checkout',exact:true})).toHaveCount(0)
  } finally { await browser.close() }
})
