#!/usr/bin/env python3
"""Generate only KEDA PromQL lines; deployment-specific policy stays in YAML."""
from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SIGNALS = {
    "apexload_queued_vusers": "total_vusers",
    "apexload_active_vusers": "active_vusers",
    "apexload_queued_browser_vusers": "total_browser_vusers",
    "apexload_active_browser_vusers": "active_browser_vusers",
    "apexload_saturated_generators": "saturated_generators",
    "apexload_reserved_replica_floor": "reserved_replica_floor",
}
TARGETS = {
    **{f"deployments/k8s/{overlay}/generator-keda-scaledobject.yaml": "${APEXLOAD_FLEET_ID}"
       for overlay in ("aks", "eks", "onprem", "onprem-autoscaling", "onprem-ha-autoscaling")},
    "deployments/k8s/local/generator-keda-scaledobject.yaml": "apexload-local",
    "deployments/k8s/aks-azure-monitor/generator-keda-azure-monitor-patch.yaml": "${APEXLOAD_FLEET_ID}",
    "deployments/helm/apexload/templates/keda.yaml": '{{ include "apexload.fleetID" . }}',
}
NOTICE = "# Query expressions generated by scripts/generate-keda-queries.py; edit its signal definition.\n"


def expression(signal: str, fleet: str) -> str:
    return (f'max(apexload_fleet_autoscaling{{fleet="{fleet}",signal="{signal}"}} '
            'and on(fleet,job,instance) (apexload_fleet_autoscaling_valid_until > time()))')


def render(source: str, fleet: str) -> str:
    """Keep every non-query line byte-for-byte, including Helm and auth blocks."""
    lines = source.splitlines(keepends=True)
    seen: set[str] = set()
    metric: str | None = None
    for index, line in enumerate(lines):
        match = re.fullmatch(r"\s*metricName: (\S+)\s*", line)
        if match:
            if metric is not None:
                raise ValueError(f"missing query for {metric}")
            metric = match[1]
        match = re.fullmatch(r"(\s*)query: [^\n]*(\n?)", line)
        if match:
            if metric not in SIGNALS or metric in seen:
                raise ValueError(f"unknown or duplicate query metric: {metric}")
            seen.add(metric)
            lines[index] = f"{match[1]}query: {expression(SIGNALS[metric], fleet)}{match[2]}"
            metric = None
    if seen != set(SIGNALS) or metric is not None:
        raise ValueError(f"expected one query for each signal; missing {sorted(set(SIGNALS) - seen)}")
    result = "".join(lines)
    return result if result.startswith(NOTICE) else NOTICE + result


def generate(root: Path, check: bool) -> list[str]:
    # Validate every input before writing any file, so malformed new overlays
    # cannot leave a partially regenerated deployment set.
    outputs = {path: render((root / path).read_text(), fleet) for path, fleet in TARGETS.items()}
    stale = [path for path, output in outputs.items() if (root / path).read_text() != output]
    if not check:
        for path in stale:
            (root / path).write_text(outputs[path])
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated query lines are stale")
    args = parser.parse_args()
    stale = generate(ROOT, args.check)
    if args.check and stale:
        print("Run python3 scripts/generate-keda-queries.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
