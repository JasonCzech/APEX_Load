#!/usr/bin/env python3
"""Generate the repository-owned QA dashboard from tracker source files."""

from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import sys

from qa_metrics import render_table as render_metric_table
from qa_lane_status import render_lane_status


def markdown_table(document: str, heading: str) -> list[str]:
    lines = document.splitlines()
    try:
        start = lines.index(heading) + 1
    except ValueError as exc:
        raise ValueError(f"missing heading {heading!r}") from exc
    table: list[str] = []
    for line in lines[start:]:
        if line.startswith("|"):
            table.append(line)
        elif table:
            break
    if len(table) < 2:
        raise ValueError(f"heading {heading!r} has no Markdown table")
    return table


def assertion_counts(matrix: str) -> Counter[str]:
    counts: Counter[str] = Counter()
    for line in markdown_table(matrix, "### Tier-0 assertion matrix")[2:]:
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) >= 3:
            counts[cells[2]] += 1
    return counts


def render(status: str, matrix: str, metrics: list[str], api_contract: dict[str, object], executions: dict | None = None) -> str:
    milestones = markdown_table(status, "## Milestones")
    counts = assertion_counts(matrix)
    contract_totals = api_contract.get("totals")
    if not isinstance(contract_totals, dict):
        raise ValueError("API contract matrix has no totals object")
    contract_green = int(contract_totals.get("green", 0))
    contract_partial = int(contract_totals.get("partial", 0))
    contract_missing = int(contract_totals.get("missing", 0))
    contract_routes = int(contract_totals.get("routes", 0))
    if contract_green + contract_partial + contract_missing != contract_routes:
        raise ValueError("API contract matrix state totals do not equal route total")
    return "\n".join(
        [
            "# QA Program Dashboard",
            "",
            "_Generated by `scripts/qa-generate-dashboard.py`; do not edit by hand._",
            "",
            "Sources: [STATUS.md](STATUS.md) · [TEST_PROGRAM.md](TEST_PROGRAM.md) · "
            "[Tier-0 matrix](E2E_SUITES.md#tier-0-assertion-matrix) · "
            "[API contract matrix](evidence/M1/api-contract-matrix.json) · "
            "[Evidence contract](evidence-contract.json)",
            "",
            "## Milestones",
            "",
            *milestones,
            "",
            "## Headline metrics",
            "",
            *metrics,
            "",
            "## Tier-0 assertion coverage",
            "",
            "| GREEN | PARTIAL | MISSING | Total |",
            "|---:|---:|---:|---:|",
            f"| {counts['GREEN']} | {counts['PARTIAL']} | {counts['MISSING']} | {sum(counts.values())} |",
            "",
            "## M1 API contract coverage",
            "",
            "| GREEN | PARTIAL | MISSING | Total |",
            "|---:|---:|---:|---:|",
            f"| {contract_green} | {contract_partial} | {contract_missing} | {contract_routes} |",
            "",
            *(render_lane_status(executions) if executions is not None else []),
            "## Gate tiers",
            "",
            "| Tier | Runs | Purpose |",
            "|---|---|---|",
            "| PR | Formatting, tests, generated-artifact freshness, coverage, dashboard, Tier-0 | Blocks regressions |",
            "| Nightly | Repeated Go/Playwright, PostgreSQL, long protocol suites | Finds flakes and integration drift |",
            "| Manual evidence | kind, performance, AKS disruption, 24/72-hour soak | Produces committed milestone evidence |",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--status", type=Path, default=Path("docs/qa/STATUS.md"))
    parser.add_argument("--matrix", type=Path, default=Path("docs/qa/E2E_SUITES.md"))
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--metrics", type=Path, help="optional metrics table input for isolated generator tests")
    parser.add_argument("--api-contract", type=Path, default=Path("docs/qa/evidence/M1/api-contract-matrix.json"))
    parser.add_argument("--executions", type=Path, default=Path("docs/qa/execution-status.json"))
    parser.add_argument("--output", type=Path, default=Path("docs/qa/DASHBOARD.md"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    generated = render(
        args.status.read_text(),
        args.matrix.read_text(),
        markdown_table(args.metrics.read_text(), "# QA Headline Metrics")
        if args.metrics
        else render_metric_table(args.root.resolve()),
        json.loads(args.api_contract.read_text()),
        json.loads(args.executions.read_text()),
    )
    if args.check:
        if not args.output.exists() or args.output.read_text() != generated:
            print(f"{args.output} is stale; run scripts/qa-generate-dashboard.py", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
