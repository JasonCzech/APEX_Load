#!/usr/bin/env python3
"""Generate the repository-owned QA dashboard from tracker source files."""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import sys


def markdown_table(document: str, heading: str) -> list[str]:
    lines = document.splitlines()
    try:
        start = lines.index(heading) + 1
    except ValueError as exc:
        raise ValueError(f"missing heading {heading!r}") from exc
    table: list[str] = []
    for line in lines[start:]:
        if line.startswith("|"):
            table.append(line)
        elif table:
            break
    if len(table) < 2:
        raise ValueError(f"heading {heading!r} has no Markdown table")
    return table


def assertion_counts(matrix: str) -> Counter[str]:
    counts: Counter[str] = Counter()
    for line in markdown_table(matrix, "# Tier-0 Assertion Matrix")[2:]:
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) >= 3:
            counts[cells[2]] += 1
    return counts


def render(status: str, matrix: str, metrics: str) -> str:
    milestones = markdown_table(status, "## Milestones")
    metric_table = markdown_table(metrics, "# QA Headline Metrics")
    counts = assertion_counts(matrix)
    return "\n".join(
        [
            "# QA Program Dashboard",
            "",
            "_Generated by `scripts/qa-generate-dashboard.py`; do not edit by hand._",
            "",
            "Sources: [STATUS.md](STATUS.md) · [TEST_PROGRAM.md](TEST_PROGRAM.md) · "
            "[Headline metrics](HEADLINE_METRICS.md) · [Tier-0 matrix](TIER0_ASSERTION_MATRIX.md) · "
            "[Evidence contract](evidence-contract.json)",
            "",
            "## Milestones",
            "",
            *milestones,
            "",
            "## Headline metrics",
            "",
            *metric_table,
            "",
            "## Tier-0 assertion coverage",
            "",
            "| GREEN | PARTIAL | MISSING | Total |",
            "|---:|---:|---:|---:|",
            f"| {counts['GREEN']} | {counts['PARTIAL']} | {counts['MISSING']} | {sum(counts.values())} |",
            "",
            "## Gate tiers",
            "",
            "| Tier | Runs | Purpose |",
            "|---|---|---|",
            "| PR | Formatting, tests, generated-artifact freshness, coverage, dashboard, Tier-0 | Blocks regressions |",
            "| Nightly | Repeated Go/Playwright, PostgreSQL, long protocol suites | Finds flakes and integration drift |",
            "| Manual evidence | kind, performance, AKS disruption, 24/72-hour soak | Produces committed milestone evidence |",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--status", type=Path, default=Path("docs/qa/STATUS.md"))
    parser.add_argument("--matrix", type=Path, default=Path("docs/qa/TIER0_ASSERTION_MATRIX.md"))
    parser.add_argument("--metrics", type=Path, default=Path("docs/qa/HEADLINE_METRICS.md"))
    parser.add_argument("--output", type=Path, default=Path("docs/qa/DASHBOARD.md"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    generated = render(args.status.read_text(), args.matrix.read_text(), args.metrics.read_text())
    if args.check:
        if not args.output.exists() or args.output.read_text() != generated:
            print(f"{args.output} is stale; run scripts/qa-generate-dashboard.py", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
