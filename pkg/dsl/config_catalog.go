// ConfigGroups returns a copy of the canonical 7-group taxonomy.
func ConfigGroups() []ConfigGroupMeta {
	return slices.Clone(canonicalConfigGroups)
}

// ConfigCatalog returns a copy of all canonical ScriptConfig field metadata entries.
func ConfigCatalog() []ConfigFieldMeta {
	out := make([]ConfigFieldMeta, len(canonicalConfigCatalog))
	for i, entry := range canonicalConfigCatalog {
		out[i] = cloneConfigFieldMeta(entry)
	}
	return out
}

// ConfigFieldForPath looks up a single ConfigFieldMeta by its canonical dotted path.
func ConfigFieldForPath(path string) (ConfigFieldMeta, bool) {
	idx, ok := canonicalConfigIndex[strings.TrimSpace(path)]
	if !ok {
		return ConfigFieldMeta{}, false
	}
	return cloneConfigFieldMeta(canonicalConfigCatalog[idx]), true
}

// ConfigCatalogForFilter returns catalog entries matching optional protocol and scope filters.
func ConfigCatalogForFilter(protocol, scope string) []ConfigFieldMeta {
	protocol = strings.ToLower(strings.TrimSpace(protocol))
	scope = strings.ToLower(strings.TrimSpace(scope))
	if protocol != "" && protocol != "*" && !catalogHasExplicitProtocol(protocol, scope) {
		// Versioned aliases (http/1.1, http/2, http/3) are HTTP-family scripts.
		protocol = ProtocolFamily(protocol)
	}
	if protocol != "" && protocol != "*" && !catalogHasExplicitProtocol(protocol, scope) {
		return nil
	}
	var out []ConfigFieldMeta
	for _, entry := range canonicalConfigCatalog {
		if protocol != "" && !configFieldMatchesProtocol(entry, protocol) {
			continue
		}
		if scope != "" && !slices.Contains(entry.Scopes, scope) {
			continue
		}
		out = append(out, cloneConfigFieldMeta(entry))
	}
	return out
}

func catalogHasExplicitProtocol(protocol, scope string) bool {
	for _, entry := range canonicalConfigCatalog {
		if scope != "" && !slices.Contains(entry.Scopes, scope) {
			continue
		}
		for _, p := range entry.Protocols {
			if p == "*" {
				continue
			}
			if strings.EqualFold(p, protocol) {
				return true
			}
			if strings.HasPrefix(protocol, "jms") && strings.HasPrefix(strings.ToLower(p), "jms") {
				return true
			}
		}
	}
	return false
}

func configFieldMatchesProtocol(entry ConfigFieldMeta, protocol string) bool {
	for _, p := range entry.Protocols {
		if p == "*" || strings.EqualFold(p, protocol) {
			return true
		}
		if strings.HasPrefix(protocol, "jms") && strings.HasPrefix(strings.ToLower(p), "jms") {
			return true
		}
	}
	return false
}

func cloneConfigFieldMeta(in ConfigFieldMeta) ConfigFieldMeta {
	in.Options = slices.Clone(in.Options)
	in.Protocols = slices.Clone(in.Protocols)
	in.Scopes = slices.Clone(in.Scopes)
	return in
}

var canonicalConfigIndex = func() map[string]int {
	m := make(map[string]int, len(canonicalConfigCatalog))
	for i, f := range canonicalConfigCatalog {
		m[f.Path] = i
	}
	return m
}()

