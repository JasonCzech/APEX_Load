package sample

import (
	"encoding/json"
	"strings"
	"testing"
)

func pseudoHeaderHAR(t *testing.T, url string, headers []map[string]any) string {
	t.Helper()
	list := make([]any, 0, len(headers))
	for _, header := range headers {
		list = append(list, header)
	}
	data, err := json.Marshal(map[string]any{"log": map[string]any{"entries": []any{map[string]any{
		"request":  map[string]any{"method": "POST", "url": url, "httpVersion": "http/2.0", "headers": list, "postData": map[string]any{"mimeType": "application/x-www-form-urlencoded", "text": "message=%7B%7D"}},
		"response": map[string]any{"status": 200, "httpVersion": "http/2.0", "content": map[string]any{"text": "{}"}},
	}}}})
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func header(name, value string) map[string]any { return map[string]any{"name": name, "value": value} }

// Chrome and LoadRunner HAR exports restate the request line as HTTP/2
// pseudo-headers. Agreeing occurrences are regenerated by the transport and
// must not block execution; any disagreement still requires review.
func TestHARPseudoHeadersNormalizeOnlyWhenTheyAgreeWithTheRequestLine(t *testing.T) {
	const target = "https://org.example.invalid:443/aura?r=12&aura.ApexAction.execute=1"
	agreeing := []map[string]any{header(":method", "POST"), header(":authority", "ORG.example.invalid"), header(":scheme", "https"), header(":path", "/aura?r=12&aura.ApexAction.execute=1"), header("Accept", "*/*")}
	for _, tc := range []struct {
		name    string
		headers []map[string]any
		gated   bool
	}{
		{"agreeing", agreeing, false},
		{"authority disagrees", []map[string]any{header(":method", "POST"), header(":authority", "other.example.invalid"), header(":path", "/aura?r=12&aura.ApexAction.execute=1"), header("Accept", "*/*")}, true},
		{"path disagrees", []map[string]any{header(":method", "POST"), header(":path", "/aura?r=13"), header("Accept", "*/*")}, true},
		{"unknown pseudo-header", []map[string]any{header(":method", "POST"), header(":protocol", "websocket"), header("Accept", "*/*")}, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			result, err := Convert(ImportRequest{Format: "har", Content: pseudoHeaderHAR(t, target, tc.headers)})
			if err != nil {
				t.Fatal(err)
			}
			action := result.Script.Actions[0]
			gated := action.Metadata["execution_blocker"] != nil
			if gated != tc.gated {
				t.Fatalf("gated=%v want %v metadata=%v", gated, tc.gated, action.Metadata)
			}
			kept := false
			for _, header := range action.HeaderList {
				if header.Name == "Accept" && header.Value == "*/*" {
					kept = true
				}
				if !tc.gated && strings.HasPrefix(header.Name, ":") {
					t.Fatalf("agreeing pseudo-header %q was retained", header.Name)
				}
			}
			if !kept {
				t.Fatal("ordinary header was dropped")
			}
			for name := range action.Headers {
				if !tc.gated && strings.HasPrefix(name, ":") {
					t.Fatalf("agreeing pseudo-header %q retained in header map", name)
				}
			}
		})
	}
}
