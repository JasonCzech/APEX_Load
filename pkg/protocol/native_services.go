// NativeDataRequest contains semantic arguments only. Execution identity,
// credentials, mutation sequences and lease tokens never cross this boundary.
// All strings are literal; adapters must not evaluate template expressions.
type NativeDataRequest struct {
	Alias           string            `json:"alias"`
	Operation       string            `json:"operation"`
	RecordID        string            `json:"record_id,omitempty"`
	Position        int               `json:"position,omitempty"`
	Columns         []string          `json:"columns,omitempty"`
	Values          map[string]string `json:"values,omitempty"`
	Expected        map[string]string `json:"expected,omitempty"`
	ExpectedVersion string            `json:"expected_version,omitempty"`
	Delta           string            `json:"delta,omitempty"`
	WaitMS          int               `json:"wait_ms,omitempty"`
	LeaseMS         int               `json:"lease_ms,omitempty"`
	Limit           int               `json:"limit,omitempty"`
	Cursor          string            `json:"cursor,omitempty"`
	LeaseRef        string            `json:"lease_ref,omitempty"`
}

type NativeDataRow struct {
	ID      string            `json:"id,omitempty"`
	Version string            `json:"version"`
	Values  map[string]string `json:"values"`
}
type NativeDataCell struct {
	Present bool   `json:"present"`
	Value   string `json:"value,omitempty"`
}
type NativeDataResult struct {
	Status   string           `json:"status"`
	Revision string           `json:"revision"`
	Row      *NativeDataRow   `json:"row,omitempty"`
	Rows     []NativeDataRow  `json:"rows,omitempty"`
	Cells    []NativeDataCell `json:"cells,omitempty"`
	Columns  []string         `json:"columns,omitempty"`
	Value    string           `json:"value,omitempty"`
	Count    string           `json:"count"`
	LeaseRef string           `json:"lease_ref,omitempty"`
}

// NativeDataError deliberately exposes a bounded code, never an input value.
type NativeDataError struct {
	Code           string `json:"code"`
	OutcomeUnknown bool   `json:"outcome_unknown,omitempty"`
}

func (e *NativeDataError) Error() string { return "native data service: " + e.Code }

// NativeServices is bound once to one trusted VUser/lane. Invocation IDs are
// generated by the runner adapter, not by guest code. Call sequence numbers are
// channel replay identities; they are independent from core mutation sequences.
type NativeServices interface {
	BeginInvocation(context.Context, string) (NativeInvocation, error)
}
type NativeInvocation interface {
	Call(context.Context, uint64, NativeDataRequest) (NativeDataResult, error)
	Done() <-chan struct{}
	Err() error
	Close()
}
type RuntimeNativeServicesSetter interface {
	SetRuntimeNativeServices(NativeServices) error
}
