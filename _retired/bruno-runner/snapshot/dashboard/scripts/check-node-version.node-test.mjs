import assert from 'node:assert/strict'
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { readdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import test from 'node:test'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { assertNodeVersion, readPinnedNodeVersion, requiredNodeVersion } from './check-node-version.mjs'

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// Derive the rejected version from the pin instead of repeating a literal, so a
// correct `.nvmrc` bump does not turn CI red inside the very test that is
// supposed to police the bump.
const differentNodeVersion = requiredNodeVersion.replace(/\d+$/, (patch) => String(Number(patch) + 1))

test('accepts the repository Node.js version', () => {
  assert.doesNotThrow(() => assertNodeVersion(requiredNodeVersion))
})

test('rejects a different Node.js version', () => {
  assert.notEqual(differentNodeVersion, requiredNodeVersion, 'the rejected fixture must differ from the pin')
  assert.throws(
    () => assertNodeVersion(differentNodeVersion),
    new RegExp(`requires Node\\.js ${escapeRegExp(requiredNodeVersion)}; found ${escapeRegExp(differentNodeVersion)}`),
  )
})

// The Node pin is duplicated outside .nvmrc, and the assertions below cover
// every copy this file can reach: dashboard engines.node, every `FROM node:`
// builder image (the root Dockerfile plus each runners/*/Dockerfile), any
// distroless Node *runtime* image those Dockerfiles ship (held to the major,
// which is all a distroless tag carries), and every setup-node pin under
// .github — the workflows *and* the composite actions in .github/actions, which
// ship to downstream consumers of the published action.
// Nothing else in the repository reads .nvmrc, so an unasserted copy goes
// silently stale and contributors, CI and the container build disagree.
//
// Two copies are deliberately out of scope and are NOT guaranteed by this file:
// dashboard/package-lock.json restates engines.node but is regenerated by npm,
// and README.md's Requirements line is prose. Bumping the pin still means
// grepping the repository for the old version.
//
// One shape is out of reach rather than out of scope: a Dockerfile whose builder
// image arrives entirely from outside the file (`ARG NODE_IMAGE` with no default
// plus `FROM ${NODE_IMAGE}`, supplied by `--build-arg`) carries no version to
// read, so no assertion here can hold it to the pin. Every shape that does write
// the tag into the file is either parsed or reported.
const repositoryRoot = new URL('../../', import.meta.url)
const readRepositoryFile = (relativePath) => readFileSync(new URL(relativePath, repositoryRoot), 'utf8')
// Slice the hrefs rather than using path.relative so the reported paths stay
// '/'-separated on every platform the dashboard suite runs on.
const repositoryPath = (fileUrl) => fileUrl.href.slice(repositoryRoot.href.length)

// Collect *.yml/*.yaml recursively so composite actions under .github/actions
// are covered too. Scoping this to .github/workflows/ left the pin in
// .github/actions/apexload-run/action.yml unasserted by anything in the
// repository.
const collectYamlFiles = async (directoryUrl) => {
  const collected = []
  for (const entry of (await readdir(fileURLToPath(directoryUrl), { withFileTypes: true })).sort((left, right) =>
    left.name.localeCompare(right.name),
  )) {
    if (entry.isDirectory()) {
      collected.push(...(await collectYamlFiles(new URL(`${entry.name}/`, directoryUrl))))
    } else if (entry.name.endsWith('.yml') || entry.name.endsWith('.yaml')) {
      collected.push(new URL(entry.name, directoryUrl))
    }
  }
  return collected
}

// Collect the setup-node pins in one YAML definition. The value is anchored to
// the key's own line with `[ \t]*` rather than `\s*`, because `\s` matches
// newlines: with `\s*` a `node-version:` mapping key whose value is a nested
// block — how a composite action under .github/actions declares it as an
// *input* — runs past the newline and captures the next line's `description:`
// as if it were a pinned version. Every real pin in the repository is written
// `node-version: <value>` on one line.
const collectNodeVersionPins = (definition) =>
  [...definition.matchAll(/^[ \t]*node-version:[ \t]*['"]?([^'"\s#]+)/gm)].map((match) => match[1])

// Enumerate the Dockerfiles that CI builds: the root release image plus every
// runners/*/Dockerfile. Discovering the runner images rather than listing them
// means a new runner cannot arrive with an unguarded `FROM node:` pin, which is
// how runners/bruno/Dockerfile stayed unasserted. Discovery alone is not enough,
// though: reaching a file only guards it if its builder line is also parsed, so
// the pins are read with `collectBuilderNodeImages` and cross-checked below.
const collectDockerfiles = () => {
  const dockerfiles = [new URL('Dockerfile', repositoryRoot)]
  const runnersUrl = new URL('runners/', repositoryRoot)
  for (const entry of readdirSync(fileURLToPath(runnersUrl), { withFileTypes: true }).sort((left, right) =>
    left.name.localeCompare(right.name),
  )) {
    if (!entry.isDirectory()) {
      continue
    }
    const candidate = new URL(`${entry.name}/Dockerfile`, runnersUrl)
    if (existsSync(candidate)) {
      dockerfiles.push(candidate)
    }
  }
  return dockerfiles
}

// Read the `FROM node:<tag>` builder pins out of one Dockerfile. The pattern has
// to be as permissive as the grammar it parses: Docker lets an instruction be
// indented, treats the `FROM` keyword case-insensitively, accepts any run of
// spaces or tabs as the separator, and permits `--flag` arguments
// (`--platform=$BUILDPLATFORM`) between the keyword and the image reference. A
// whitespace-exact `/^FROM node:/` reads zero images out of every one of those
// valid shapes, and a Dockerfile that yields zero images drops out of the
// version assertion below in complete silence — so reshaping the line, not
// bumping the pin, was enough to ship a runner built on an unpinned Node.
const collectBuilderNodeImages = (contents) =>
  [...contents.matchAll(/^[ \t]*FROM[ \t]+(?:--\S+[ \t]+)*node:([^\s@]+)/gim)].map((match) => match[1])

// Deliberately loose companion to the above, and the same guard the distroless
// test below gets from its `contents.includes('distroless/nodejs')` check: count
// every `FROM` line that mentions a `node:` image in any shape at all. Requiring
// the parsed count to equal this one turns a builder line the parser cannot read
// — a registry-prefixed mirror of the image, say — into a loud failure instead
// of a silently unasserted image.
const countLooseBuilderNodeReferences = (contents) => [...contents.matchAll(/^[ \t]*FROM[ \t].*\bnode:/gim)].length

test('reads the pinned version from .nvmrc', () => {
  // Re-derive the expectation from the file bytes rather than calling the reader
  // a second time: `requiredNodeVersion` *is* `readPinnedNodeVersion()`, so
  // comparing the two would compare a value with itself and never fail — not
  // even if the reader were repointed at a different file entirely. Normalise
  // the same way nvm does, so a valid `v`-prefixed pin is not reported as drift.
  assert.equal(readRepositoryFile('.nvmrc').trim().replace(/^v/, ''), requiredNodeVersion)
})

test('readPinnedNodeVersion trims whitespace and strips the leading v that nvm accepts', (t) => {
  const fixtureDirectory = mkdtempSync(join(tmpdir(), 'apexload-nvmrc-'))
  t.after(() => rmSync(fixtureDirectory, { recursive: true, force: true }))
  const fixture = join(fixtureDirectory, '.nvmrc')
  // Deliberately unlike the repository pin, so this also proves the reader reads
  // the file it is handed instead of returning the module-level constant.
  writeFileSync(fixture, '  v9.8.7\n', 'utf8')

  assert.equal(readPinnedNodeVersion(pathToFileURL(fixture)), '9.8.7')
})

test('rejects an .nvmrc that is not an exact version', () => {
  const looseVersionFile = new URL('../package.json', import.meta.url)
  assert.throws(() => readPinnedNodeVersion(looseVersionFile), /must contain an exact Node\.js version/)
})

test('reports a readable error when .nvmrc is missing', () => {
  assert.throws(
    () => readPinnedNodeVersion(new URL('.nvmrc-does-not-exist', repositoryRoot)),
    /Unable to read the pinned Node\.js version from .*\.nvmrc-does-not-exist/,
  )
})

test('dashboard engines.node matches the pinned version', () => {
  const manifest = JSON.parse(readRepositoryFile('dashboard/package.json'))
  assert.equal(manifest.engines?.node, requiredNodeVersion)
})

test('a builder FROM line is parsed in every shape Docker accepts', () => {
  // Each line below is a valid Dockerfile builder stage that a whitespace-exact
  // `/^FROM node:/` parsed as zero images. Zero images is not a failure — it is
  // an absence — so each of these shipped a runner whose Node pin nothing in the
  // repository checked, while `npm run test:node-version` stayed green.
  const tag = '20.0.0-bookworm-slim'
  for (const line of [
    `FROM node:${tag} AS build`,
    `FROM --platform=$BUILDPLATFORM node:${tag} AS build`,
    `FROM --platform=$BUILDPLATFORM --a=b node:${tag} AS build`,
    `FROM  node:${tag} AS build`,
    `FROM\tnode:${tag} AS build`,
    `from node:${tag} AS build`,
    `  FROM node:${tag} AS build`,
  ]) {
    assert.deepEqual(collectBuilderNodeImages(`${line}\n`), [tag], `failed to parse ${JSON.stringify(line)}`)
  }

  // The digest form the root Dockerfile uses must still stop the tag at the `@`,
  // or the tag would never equal the pin and every run would fail.
  assert.deepEqual(collectBuilderNodeImages('FROM node:22.0.0-alpine3.23@sha256:abc AS dashboard-builder\n'), [
    '22.0.0-alpine3.23',
  ])
  // Non-node builders and the distroless *runtime* stage are not builder pins:
  // the runtime image is held to its major by the distroless test below, and
  // widening this parser onto it would compare a major-only tag to a full pin.
  assert.deepEqual(
    collectBuilderNodeImages('FROM golang:1.26.5-alpine3.24 AS builder\nFROM gcr.io/distroless/nodejs22-debian13:nonroot\n'),
    [],
  )
})

test('a builder image this test cannot parse is reported rather than dropped', () => {
  // A reference the parser cannot read still has to fail loudly. Counting the
  // loose `FROM ... node:` lines and requiring the parsed count to match is what
  // turns "no images found" from silent success into a reported mismatch.
  const registryMirrored = 'FROM registry.example.com/mirror/node:20.0.0 AS build\n'
  assert.deepEqual(collectBuilderNodeImages(registryMirrored), [])
  assert.equal(countLooseBuilderNodeReferences(registryMirrored), 1)

  // ARG indirection moves the tag off the FROM line, so no FROM-line pattern can
  // reach it and the loose count agrees with the parser at zero. The file-level
  // `node:` mention is the only thing left that catches it.
  const argIndirected = 'ARG NODE_IMAGE=node:20.0.0-bookworm-slim\nFROM ${NODE_IMAGE} AS build\n'
  assert.deepEqual(collectBuilderNodeImages(argIndirected), [])
  assert.equal(countLooseBuilderNodeReferences(argIndirected), 0)
  assert.ok(argIndirected.includes('node:'))

  // And the loose count must not fire on Dockerfiles that build no Node image,
  // or runners/java_vuser/Dockerfile would fail for having no builder pin.
  assert.equal(countLooseBuilderNodeReferences('FROM alpine:3.24\nRUN node --version\n'), 0)
  assert.equal(countLooseBuilderNodeReferences('FROM gcr.io/distroless/nodejs22-debian13:nonroot\n'), 0)
})

test('every Node builder image matches the pinned version', () => {
  const dockerfiles = collectDockerfiles()
  assert.ok(
    dockerfiles.some((fileUrl) => repositoryPath(fileUrl).startsWith('runners/')),
    'expected the scan to reach runners/*/Dockerfile, not just the root Dockerfile',
  )

  const images = []
  for (const fileUrl of dockerfiles) {
    const dockerfile = repositoryPath(fileUrl)
    const contents = readFileSync(fileUrl, 'utf8')
    const tags = collectBuilderNodeImages(contents)

    // Both cross-checks exist because the failure mode here is silence: an
    // unparsed builder line contributes no entries and vanishes from the
    // per-image assertion below, and only the root Dockerfile has an existence
    // backstop. The first catches a `FROM` line whose image reference the parser
    // cannot read; the second catches the tag being moved off the `FROM` line
    // altogether, as `ARG NODE_IMAGE=node:20` + `FROM ${NODE_IMAGE}` does.
    assert.equal(
      tags.length,
      countLooseBuilderNodeReferences(contents),
      `${dockerfile} names a Node builder image in a shape this test cannot parse`,
    )
    assert.equal(
      tags.length > 0,
      contents.includes('node:'),
      `${dockerfile} mentions a node: image that no builder assertion holds to the pin`,
    )

    for (const tag of tags) {
      images.push({ dockerfile, tag })
    }
  }

  assert.ok(images.length > 0, 'expected at least one Dockerfile to build on a node image')
  assert.ok(
    images.some((image) => image.dockerfile === 'Dockerfile'),
    'expected the root Dockerfile to build the dashboard on a node image',
  )
  for (const image of images) {
    assert.equal(
      image.tag.split('-')[0],
      requiredNodeVersion,
      `${image.dockerfile} node image ${image.tag} does not use the pinned Node.js ${requiredNodeVersion}`,
    )
  }
})

// The builder assertion above matches `FROM node:`, so it structurally cannot
// see a distroless runtime stage — and that stage is the Node that actually
// executes the shipped runner (runners/bruno/Dockerfile builds on `FROM node:`
// and then runs on `gcr.io/distroless/nodejsNN-...`). Left unasserted, a
// `.nvmrc` major bump is satisfied by updating the builder stage alone, which
// ships a node_modules tree installed under one Node major into an image that
// runs another. Distroless publishes major-only tags, so the major is all that
// can be held here.
test('every distroless Node runtime image matches the pinned major version', () => {
  const requiredMajor = requiredNodeVersion.split('.')[0]

  for (const fileUrl of collectDockerfiles()) {
    const dockerfile = repositoryPath(fileUrl)
    const contents = readFileSync(fileUrl, 'utf8')
    const majors = [...contents.matchAll(/^FROM\s+(?:--\S+\s+)*\S*distroless\/nodejs(\d+)/gm)].map((match) => match[1])

    // Detect the reference with a plain substring as well, so an image name
    // reshaped past the pattern above fails loudly here instead of silently
    // dropping out of the version assertion.
    assert.equal(
      majors.length > 0,
      contents.includes('distroless/nodejs'),
      `${dockerfile} references a distroless Node image in a shape this test cannot parse`,
    )

    for (const major of majors) {
      assert.equal(
        major,
        requiredMajor,
        `${dockerfile} runtime image distroless/nodejs${major} does not use the pinned Node.js major ${requiredMajor}`,
      )
    }
  }
})

test('a node-version composite-action input declaration is not read as a pin', () => {
  // Naming a composite-action input `node-version` is an ordinary edit, and
  // .github/actions is in scope for the scan below. The declaration is a
  // mapping key whose value is a nested block, so it carries no version to
  // check — reporting `description:` as the pinned version would fail the scan
  // with a message pointing at a pin that does not exist.
  assert.deepEqual(
    collectNodeVersionPins(
      [
        'inputs:',
        '  node-version:',
        "    description: 'Node.js version for the dashboard build'",
        '    required: false',
        '',
      ].join('\n'),
    ),
    [],
  )
  // The real shapes still have to be collected, quoted or not.
  assert.deepEqual(
    collectNodeVersionPins(['      with:', `        node-version: ${requiredNodeVersion}`, ''].join('\n')),
    [requiredNodeVersion],
  )
  assert.deepEqual(
    collectNodeVersionPins(['      with:', `        node-version: '${requiredNodeVersion}'`, ''].join('\n')),
    [requiredNodeVersion],
  )
})

test('every setup-node pin under .github matches the pinned version', async () => {
  const githubUrl = new URL('.github/', repositoryRoot)
  const files = await collectYamlFiles(githubUrl)
  assert.ok(
    files.some((fileUrl) => repositoryPath(fileUrl).startsWith('.github/actions/')),
    'expected the scan to reach composite actions under .github/actions, not just .github/workflows',
  )

  const pins = []
  for (const fileUrl of files) {
    for (const version of collectNodeVersionPins(readFileSync(fileUrl, 'utf8'))) {
      pins.push({ definition: repositoryPath(fileUrl), version })
    }
  }

  assert.ok(pins.length > 0, 'expected at least one setup-node pin under .github')
  assert.ok(
    pins.some((pin) => pin.definition.startsWith('.github/workflows/')),
    'expected at least one setup-node pin across .github/workflows',
  )
  for (const pin of pins) {
    assert.equal(
      pin.version,
      requiredNodeVersion,
      `${pin.definition} pins node-version ${pin.version} instead of the repository Node.js ${requiredNodeVersion}`,
    )
  }
})
