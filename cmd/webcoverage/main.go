// Command webcoverage generates docs/LOADRUNNER_COVERAGE.md, the single
// LoadRunner import coverage document, from the embedded function registries
// and the code-owned coverage detail maps in pkg/convert/enterprisearchive and
// pkg/convert/trueclient. Run via `go generate ./pkg/convert/enterprisearchive`.
//
// Sections (in order): Web function coverage, Java LR function coverage,
// TruClient step coverage, Java Vuser import coverage.
//
//	-out PATH   output path (default docs/LOADRUNNER_COVERAGE.md)
//	-check      do not write; exit 1 if the file at -out differs from the output
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/jasonczech/apexload/pkg/convert/enterprisearchive"
	"github.com/jasonczech/apexload/pkg/convert/trueclient"
)

const defaultOut = "docs/LOADRUNNER_COVERAGE.md"

const header = "# LoadRunner Coverage\n\n" +
	"<!-- Generated by `go generate ./pkg/convert/enterprisearchive` (cmd/webcoverage). Do not edit by hand. -->\n\n" +
	"Generated evaluation of LoadRunner import coverage against the APEX Load conversion engine: " +
	"Web (HTTP/HTML) functions, Java Vuser `lr` API functions, TruClient steps, and Java Vuser import surfaces.\n\n"

// render assembles the full, deterministic coverage document.
func render() string {
	sections := []string{
		enterprisearchive.RenderWebHTTPFunctionCoverageMarkdown(),
		enterprisearchive.RenderJavaLRFunctionCoverageMarkdown(),
		trueclient.RenderStepCoverageMarkdown(),
		enterprisearchive.RenderJavaImportSurfaceCoverageMarkdown(),
	}
	var b strings.Builder
	b.WriteString(header)
	for i, s := range sections {
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString(strings.TrimRight(s, "\n"))
		b.WriteString("\n")
	}
	return b.String()
}

func main() {
	out := flag.String("out", defaultOut, "output markdown path")
	check := flag.Bool("check", false, "verify the file at -out is up to date instead of writing it")
	flag.Parse()

	content := render()
	if *check {
		got, err := os.ReadFile(*out)
		if err != nil || string(got) != content {
			fmt.Fprintf(os.Stderr, "webcoverage: %s is stale; run `go generate ./pkg/convert/enterprisearchive`\n", *out)
			os.Exit(1)
		}
		fmt.Printf("%s is up to date\n", *out)
		return
	}
	if err := os.WriteFile(*out, []byte(content), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "webcoverage: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s\n", *out)
}
