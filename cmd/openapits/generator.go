package main

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

var httpMethods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

type openAPIDocument struct {
	OpenAPI    string               `yaml:"openapi"`
	Components openAPIComponents    `yaml:"components"`
	Paths      map[string]*pathItem `yaml:"paths"`
}

type openAPIComponents struct {
	Schemas map[string]*schema `yaml:"schemas"`
}

type pathItem struct {
	Parameters []parameter `yaml:"parameters"`
	Get        *operation  `yaml:"get"`
	Put        *operation  `yaml:"put"`
	Post       *operation  `yaml:"post"`
	Delete     *operation  `yaml:"delete"`
	Options    *operation  `yaml:"options"`
	Head       *operation  `yaml:"head"`
	Patch      *operation  `yaml:"patch"`
	Trace      *operation  `yaml:"trace"`
}

func (p *pathItem) operation(method string) *operation {
	if p == nil {
		return nil
	}
	switch method {
	case "get":
		return p.Get
	case "put":
		return p.Put
	case "post":
		return p.Post
	case "delete":
		return p.Delete
	case "options":
		return p.Options
	case "head":
		return p.Head
	case "patch":
		return p.Patch
	case "trace":
		return p.Trace
	default:
		return nil
	}
}

type operation struct {
	OperationID string               `yaml:"operationId"`
	Parameters  []parameter          `yaml:"parameters"`
	RequestBody *requestBody         `yaml:"requestBody"`
	Responses   map[string]*response `yaml:"responses"`
}

type parameter struct {
	Ref      string  `yaml:"$ref"`
	Name     string  `yaml:"name"`
	In       string  `yaml:"in"`
	Required bool    `yaml:"required"`
	Schema   *schema `yaml:"schema"`
}

type requestBody struct {
	Ref      string               `yaml:"$ref"`
	Required bool                 `yaml:"required"`
	Content  map[string]mediaType `yaml:"content"`
}

type response struct {
	Ref     string               `yaml:"$ref"`
	Headers map[string]header    `yaml:"headers"`
	Content map[string]mediaType `yaml:"content"`
}

type header struct {
	Required bool                 `yaml:"required"`
	Schema   *schema              `yaml:"schema"`
	Content  map[string]mediaType `yaml:"content"`
}

type mediaType struct {
	Schema *schema `yaml:"schema"`
}

type schema struct {
	Ref                  string               `yaml:"$ref"`
	Type                 schemaType           `yaml:"type"`
	Format               string               `yaml:"format"`
	Properties           map[string]*schema   `yaml:"properties"`
	Required             []string             `yaml:"required"`
	Items                *schema              `yaml:"items"`
	AdditionalProperties additionalProperties `yaml:"additionalProperties"`
	Enum                 []any                `yaml:"enum"`
	Nullable             bool                 `yaml:"nullable"`
	OneOf                []*schema            `yaml:"oneOf"`
	AnyOf                []*schema            `yaml:"anyOf"`
	AllOf                []*schema            `yaml:"allOf"`
}

type schemaType []string

func (t *schemaType) UnmarshalYAML(node *yaml.Node) error {
	switch node.Kind {
	case yaml.ScalarNode:
		*t = schemaType{node.Value}
		return nil
	case yaml.SequenceNode:
		values := make([]string, 0, len(node.Content))
		for _, child := range node.Content {
			if child.Kind != yaml.ScalarNode {
				return fmt.Errorf("schema type entries must be strings")
			}
			values = append(values, child.Value)
		}
		*t = values
		return nil
	default:
		return fmt.Errorf("schema type must be a string or string array")
	}
}

type additionalProperties struct {
	Present bool
	Allowed bool
	Schema  *schema
}

func (a *additionalProperties) UnmarshalYAML(node *yaml.Node) error {
	a.Present = true
	if node.Kind == yaml.ScalarNode {
		var allowed bool
		if err := node.Decode(&allowed); err != nil {
			return fmt.Errorf("additionalProperties must be a boolean or schema: %w", err)
		}
		a.Allowed = allowed
		return nil
	}
	if node.Kind != yaml.MappingNode {
		return fmt.Errorf("additionalProperties must be a boolean or schema")
	}
	var value schema
	if err := node.Decode(&value); err != nil {
		return err
	}
	a.Allowed = true
	a.Schema = &value
	return nil
}

type locatedOperation struct {
	Path           string
	Method         string
	Operation      *operation
	PathParameters []parameter
}

func generateTransportTypes(input []byte) ([]byte, error) {
	var document openAPIDocument
	if err := yaml.Unmarshal(input, &document); err != nil {
		return nil, fmt.Errorf("parse OpenAPI YAML: %w", err)
	}
	operations, err := collectOperations(&document)
	if err != nil {
		return nil, err
	}

	var out strings.Builder
	out.Grow(len(input))
	out.WriteString("/**\n")
	out.WriteString(" * Generated from docs/swagger.yaml by cmd/openapits.\n")
	out.WriteString(" * Do not edit this file directly; run `npm run contracts:generate`.\n")
	out.WriteString(" * Empty or open-ended OpenAPI schemas intentionally become `unknown`.\n")
	out.WriteString(" */\n\n")

	writeComponents(&out, document.Components)
	out.WriteString("\n")
	writeOperations(&out, operations)
	out.WriteString("\n")
	writePaths(&out, operations)
	out.WriteString("\n")
	out.WriteString("export type ApiPath = keyof paths;\n")
	out.WriteString("export type ApiOperationId = keyof operations;\n")
	out.WriteString("\n")
	out.WriteString("export type JsonRequestBody<OperationId extends ApiOperationId> =\n")
	out.WriteString("  NonNullable<operations[OperationId][\"requestBody\"]> extends { content: { \"application/json\": infer Body } }\n")
	out.WriteString("    ? Body\n")
	out.WriteString("    : unknown;\n")
	out.WriteString("\n")
	out.WriteString("export type SuccessResponseStatus<OperationId extends ApiOperationId> =\n")
	out.WriteString("  Extract<keyof operations[OperationId][\"responses\"], `2${number}${number}`>;\n")
	out.WriteString("\n")
	out.WriteString("export type JsonSuccessResponseBody<\n")
	out.WriteString("  OperationId extends ApiOperationId,\n")
	out.WriteString("  Status extends SuccessResponseStatus<OperationId>,\n")
	out.WriteString("> = operations[OperationId][\"responses\"][Status] extends { content: { \"application/json\": infer Body } }\n")
	out.WriteString("  ? Body\n")
	out.WriteString("  : unknown;\n")

	return []byte(out.String()), nil
}

func collectOperations(document *openAPIDocument) ([]locatedOperation, error) {
	if document.OpenAPI == "" {
		return nil, fmt.Errorf("document does not declare an OpenAPI version")
	}
	if len(document.Paths) == 0 {
		return nil, fmt.Errorf("document does not declare any paths")
	}

	paths := sortedKeys(document.Paths)
	seenOperationIDs := make(map[string]string)
	operations := make([]locatedOperation, 0)
	for _, path := range paths {
		item := document.Paths[path]
		for _, method := range httpMethods {
			candidate := item.operation(method)
			if candidate == nil {
				continue
			}
			location := strings.ToUpper(method) + " " + path
			if candidate.OperationID == "" {
				return nil, fmt.Errorf("%s does not declare operationId", location)
			}
			if previous, exists := seenOperationIDs[candidate.OperationID]; exists {
				return nil, fmt.Errorf("operationId %q is shared by %s and %s", candidate.OperationID, previous, location)
			}
			if len(candidate.Responses) == 0 {
				return nil, fmt.Errorf("%s does not declare any responses", location)
			}
			seenOperationIDs[candidate.OperationID] = location
			operations = append(operations, locatedOperation{
				Path:           path,
				Method:         method,
				Operation:      candidate,
				PathParameters: item.Parameters,
			})
		}
	}
	if len(operations) == 0 {
		return nil, fmt.Errorf("document does not declare any operations")
	}
	return operations, nil
}

func writeComponents(out *strings.Builder, components openAPIComponents) {
	out.WriteString("export interface components {\n")
	out.WriteString("  schemas: {\n")
	for _, name := range sortedKeys(components.Schemas) {
		writeIndent(out, 2)
		out.WriteString(quote(name))
		out.WriteString(": ")
		writeSchema(out, components.Schemas[name], 2)
		out.WriteString(";\n")
	}
	out.WriteString("  };\n")
	out.WriteString("}\n")
}

func writeOperations(out *strings.Builder, operations []locatedOperation) {
	out.WriteString("export interface operations {\n")
	byID := append([]locatedOperation(nil), operations...)
	sort.Slice(byID, func(i, j int) bool {
		return byID[i].Operation.OperationID < byID[j].Operation.OperationID
	})
	for _, located := range byID {
		operation := located.Operation
		writeIndent(out, 1)
		out.WriteString(quote(operation.OperationID))
		out.WriteString(": {\n")
		writeParameters(out, mergeParameters(located.PathParameters, operation.Parameters), 2)
		writeRequestBody(out, operation.RequestBody, 2)
		writeResponses(out, operation.Responses, 2)
		writeIndent(out, 1)
		out.WriteString("};\n")
	}
	out.WriteString("}\n")
}

func writePaths(out *strings.Builder, operations []locatedOperation) {
	out.WriteString("export interface paths {\n")
	byPath := make(map[string][]locatedOperation)
	for _, operation := range operations {
		byPath[operation.Path] = append(byPath[operation.Path], operation)
	}
	for _, path := range sortedKeys(byPath) {
		writeIndent(out, 1)
		out.WriteString(quote(path))
		out.WriteString(": {\n")
		methodOperations := byPath[path]
		for _, method := range httpMethods {
			for _, located := range methodOperations {
				if located.Method != method {
					continue
				}
				writeIndent(out, 2)
				out.WriteString(quote(method))
				out.WriteString(": operations[")
				out.WriteString(quote(located.Operation.OperationID))
				out.WriteString("];\n")
			}
		}
		writeIndent(out, 1)
		out.WriteString("};\n")
	}
	out.WriteString("}\n")
}

func writeParameters(out *strings.Builder, parameters []parameter, indent int) {
	if len(parameters) == 0 {
		writeIndent(out, indent)
		out.WriteString("parameters?: never;\n")
		return
	}

	groups := make(map[string][]parameter)
	for _, value := range parameters {
		location := value.In
		if location == "" {
			location = "unknown"
		}
		groups[location] = append(groups[location], value)
	}
	writeIndent(out, indent)
	out.WriteString("parameters: {\n")
	for _, location := range orderedParameterLocations(groups) {
		values := groups[location]
		sort.Slice(values, func(i, j int) bool { return values[i].Name < values[j].Name })
		required := false
		for _, value := range values {
			required = required || value.Required
		}
		writeIndent(out, indent+1)
		out.WriteString(quote(location))
		if !required {
			out.WriteString("?")
		}
		out.WriteString(": {\n")
		for _, value := range values {
			writeIndent(out, indent+2)
			name := value.Name
			if name == "" {
				name = value.Ref
			}
			if name == "" {
				name = "unknown"
			}
			out.WriteString(quote(name))
			if !value.Required {
				out.WriteString("?")
			}
			out.WriteString(": ")
			writeSchema(out, value.Schema, indent+2)
			out.WriteString(";\n")
		}
		writeIndent(out, indent+1)
		out.WriteString("};\n")
	}
	writeIndent(out, indent)
	out.WriteString("};\n")
}

func writeRequestBody(out *strings.Builder, body *requestBody, indent int) {
	writeIndent(out, indent)
	if body == nil {
		out.WriteString("requestBody?: never;\n")
		return
	}
	out.WriteString("requestBody")
	if !body.Required {
		out.WriteString("?")
	}
	out.WriteString(": ")
	if body.Ref != "" && len(body.Content) == 0 {
		out.WriteString("unknown;\n")
		return
	}
	out.WriteString("{\n")
	writeContent(out, body.Content, indent+1)
	writeIndent(out, indent)
	out.WriteString("};\n")
}

func writeResponses(out *strings.Builder, responses map[string]*response, indent int) {
	writeIndent(out, indent)
	out.WriteString("responses: {\n")
	for _, status := range sortedKeys(responses) {
		value := responses[status]
		writeIndent(out, indent+1)
		out.WriteString(quote(status))
		out.WriteString(": ")
		if value == nil || (value.Ref != "" && len(value.Content) == 0 && len(value.Headers) == 0) {
			out.WriteString("unknown;\n")
			continue
		}
		out.WriteString("{\n")
		writeHeaders(out, value.Headers, indent+2)
		writeContent(out, value.Content, indent+2)
		writeIndent(out, indent+1)
		out.WriteString("};\n")
	}
	writeIndent(out, indent)
	out.WriteString("};\n")
}

func writeHeaders(out *strings.Builder, headers map[string]header, indent int) {
	if len(headers) == 0 {
		return
	}
	writeIndent(out, indent)
	out.WriteString("headers: {\n")
	for _, name := range sortedKeys(headers) {
		value := headers[name]
		writeIndent(out, indent+1)
		out.WriteString(quote(name))
		if !value.Required {
			out.WriteString("?")
		}
		out.WriteString(": ")
		if value.Schema != nil {
			writeSchema(out, value.Schema, indent+1)
		} else if len(value.Content) > 0 {
			out.WriteString("{\n")
			writeContent(out, value.Content, indent+2)
			writeIndent(out, indent+1)
			out.WriteString("}")
		} else {
			out.WriteString("unknown")
		}
		out.WriteString(";\n")
	}
	writeIndent(out, indent)
	out.WriteString("};\n")
}

func writeContent(out *strings.Builder, content map[string]mediaType, indent int) {
	writeIndent(out, indent)
	if len(content) == 0 {
		out.WriteString("content?: never;\n")
		return
	}
	out.WriteString("content: {\n")
	for _, mediaTypeName := range sortedKeys(content) {
		writeIndent(out, indent+1)
		out.WriteString(quote(mediaTypeName))
		out.WriteString(": ")
		writeSchema(out, content[mediaTypeName].Schema, indent+1)
		out.WriteString(";\n")
	}
	writeIndent(out, indent)
	out.WriteString("};\n")
}

func writeSchema(out *strings.Builder, value *schema, indent int) {
	if value == nil {
		out.WriteString("unknown")
		return
	}

	parts := make([]string, 0, 4)
	if value.Ref != "" {
		parts = append(parts, renderReference(value.Ref))
	}
	if len(value.OneOf) > 0 {
		parts = append(parts, renderSchemaSet(value.OneOf, indent, " | "))
	}
	if len(value.AnyOf) > 0 {
		parts = append(parts, renderSchemaSet(value.AnyOf, indent, " | "))
	}
	if len(value.AllOf) > 0 {
		parts = append(parts, renderSchemaSet(value.AllOf, indent, " & "))
	}
	if hasBaseSchema(value) {
		parts = append(parts, renderBaseSchema(value, indent))
	}
	if len(parts) == 0 {
		parts = append(parts, "unknown")
	}

	result := strings.Join(parenthesizeAll(parts), " & ")
	if value.Nullable && result != "null" {
		result = "(" + result + ") | null"
	}
	out.WriteString(result)
}

func hasBaseSchema(value *schema) bool {
	return len(value.Enum) > 0 || len(value.Type) > 0 || value.Properties != nil ||
		value.Items != nil || value.AdditionalProperties.Present
}

func renderBaseSchema(value *schema, indent int) string {
	if len(value.Enum) > 0 {
		literals := make([]string, 0, len(value.Enum))
		for _, enumValue := range value.Enum {
			literals = append(literals, renderLiteral(enumValue))
		}
		return strings.Join(literals, " | ")
	}

	types := append([]string(nil), value.Type...)
	if len(types) == 0 && (value.Properties != nil || value.AdditionalProperties.Present) {
		types = []string{"object"}
	}
	if len(types) == 0 && value.Items != nil {
		types = []string{"array"}
	}
	rendered := make([]string, 0, len(types))
	for _, schemaTypeName := range types {
		switch schemaTypeName {
		case "string":
			rendered = append(rendered, "string")
		case "integer", "number":
			rendered = append(rendered, "number")
		case "boolean":
			rendered = append(rendered, "boolean")
		case "null":
			rendered = append(rendered, "null")
		case "array":
			var item strings.Builder
			writeSchema(&item, value.Items, indent)
			rendered = append(rendered, "Array<"+item.String()+">")
		case "object":
			rendered = append(rendered, renderObjectSchema(value, indent))
		default:
			rendered = append(rendered, "unknown")
		}
	}
	if len(rendered) == 0 {
		return "unknown"
	}
	return strings.Join(rendered, " | ")
}

func renderObjectSchema(value *schema, indent int) string {
	if len(value.Properties) == 0 {
		if value.AdditionalProperties.Present && !value.AdditionalProperties.Allowed {
			return "Record<string, never>"
		}
		if value.AdditionalProperties.Schema != nil {
			var additional strings.Builder
			writeSchema(&additional, value.AdditionalProperties.Schema, indent)
			return "Record<string, " + additional.String() + ">"
		}
		return "Record<string, unknown>"
	}

	required := make(map[string]struct{}, len(value.Required))
	for _, name := range value.Required {
		required[name] = struct{}{}
	}
	var object strings.Builder
	object.WriteString("{\n")
	for _, name := range sortedKeys(value.Properties) {
		writeIndent(&object, indent+1)
		object.WriteString(quote(name))
		if _, isRequired := required[name]; !isRequired {
			object.WriteString("?")
		}
		object.WriteString(": ")
		writeSchema(&object, value.Properties[name], indent+1)
		object.WriteString(";\n")
	}
	if value.AdditionalProperties.Present && value.AdditionalProperties.Allowed {
		writeIndent(&object, indent+1)
		object.WriteString("[key: string]: unknown;\n")
	}
	writeIndent(&object, indent)
	object.WriteString("}")
	return object.String()
}

func renderSchemaSet(values []*schema, indent int, separator string) string {
	rendered := make([]string, 0, len(values))
	for _, value := range values {
		var item strings.Builder
		writeSchema(&item, value, indent)
		rendered = append(rendered, item.String())
	}
	return "(" + strings.Join(rendered, separator) + ")"
}

func parenthesizeAll(values []string) []string {
	if len(values) < 2 {
		return values
	}
	result := make([]string, len(values))
	for index, value := range values {
		result[index] = "(" + value + ")"
	}
	return result
}

func renderReference(reference string) string {
	const schemaPrefix = "#/components/schemas/"
	if !strings.HasPrefix(reference, schemaPrefix) {
		return "unknown"
	}
	name := strings.TrimPrefix(reference, schemaPrefix)
	name = strings.ReplaceAll(name, "~1", "/")
	name = strings.ReplaceAll(name, "~0", "~")
	return "components[\"schemas\"][" + quote(name) + "]"
}

func renderLiteral(value any) string {
	if value == nil {
		return "null"
	}
	encoded, err := json.Marshal(value)
	if err != nil {
		return "unknown"
	}
	return string(encoded)
}

func mergeParameters(pathParameters, operationParameters []parameter) []parameter {
	merged := make(map[string]parameter, len(pathParameters)+len(operationParameters))
	order := make([]string, 0, len(pathParameters)+len(operationParameters))
	add := func(value parameter) {
		key := value.In + "\x00" + value.Name
		if value.Ref != "" {
			key = "$ref\x00" + value.Ref
		}
		if _, exists := merged[key]; !exists {
			order = append(order, key)
		}
		merged[key] = value
	}
	for _, value := range pathParameters {
		add(value)
	}
	for _, value := range operationParameters {
		add(value)
	}
	result := make([]parameter, 0, len(order))
	for _, key := range order {
		result = append(result, merged[key])
	}
	return result
}

func orderedParameterLocations(groups map[string][]parameter) []string {
	preferred := []string{"path", "query", "header", "cookie"}
	result := make([]string, 0, len(groups))
	seen := make(map[string]struct{}, len(groups))
	for _, location := range preferred {
		if _, exists := groups[location]; exists {
			result = append(result, location)
			seen[location] = struct{}{}
		}
	}
	remainder := make([]string, 0)
	for location := range groups {
		if _, exists := seen[location]; !exists {
			remainder = append(remainder, location)
		}
	}
	sort.Strings(remainder)
	return append(result, remainder...)
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func quote(value string) string {
	return strconv.Quote(value)
}

func writeIndent(out *strings.Builder, level int) {
	out.WriteString(strings.Repeat("  ", level))
}
